// Block coarse-graining of partitioned pair dynamics on the coset tilings (milestone
// M11, the tilings slice). The line slice is code/compute/lab/coarse-block.ts; this file
// extends it to every lab {p,q} with blocks taken from the tile group's own subgroup structure.
//
// FRAME. A tile is a coset w W_J of the cell subgroup W_J = <s_0, s_1> in the (2, p, q) triangle group
// (coset-tiling.ts). The p colors are lifted from the finite quotient G = W / N, N the kernel of reducing the geometric
// representation mod l (lifted-coloring.ts), so every color class is a perfect matching M_c of the infinite tiling and
// commutes with the deck action of N. A tile's QUOTIENT CLASS is its coset g H in G (g its minimal representative mod
// l, H the image of W_J); the classes are the N-orbits of tiles. Two orientations of each matched edge are declared:
//   - 'radial': the shorter tile first, ties by the canonical order (lazy-space.ts cosetSpace, the M1 schedule);
//   - 'lifted': the tile of lower quotient class first. Every edge joins two different classes (lifted-coloring.ts
//     gates it), so this is defined, and it commutes with N: the whole dynamics is then N-periodic, and a property of
//     one block per class is a property of every block of the infinite tiling.
//
// BLOCKS (declared before any run).
//   - edge blocks E(c): the edges of color c, each a coset of the parabolic subgroup <s_0, s_2> (the edge stabilizer,
//     order 4) restricted to one perfect matching of the finite-index coloring; b = 2, cells ordered by the
//     orientation of color c.
//   - orbit blocks D(c, c'): the orbits of the finite group <M_c, M_c'>, admitted only when every orbit closes within
//     ORBIT_CAP cells (checked on one tile of every quotient class, which covers every orbit since both matchings
//     commute with N). An orbit that alternates around a vertex is the vertex star, a coset of the parabolic <s_1, s_2>.
//
// LONE-MOVER THEOREM (any graph, any matchings, any orientation; argued in the note, gated here). Let a bijective pair
// rule fix the background pair (beta, beta) and map the two one-excitation pairs {(u, beta), (beta, u)} to themselves.
// On that two-element set it is the identity or the swap, the same for both orientations, so a lone u never moves or
// swaps at every matching it meets: after tau rounds it sits at P^tau(a), P the product of the round's matchings
// (motion below). If F reads every one-u block as one letter t1 != F(background block), then two cells a, a' of one
// block whose images P^tau(a), P^tau(a') lie in different blocks give two configurations with one coarse image and two
// coarse futures: F is not lumpable at tau on the whole tiling. So lumpability under such an F needs P^tau to map
// every block onto a block; under the lifted coloring that is decided on one block per quotient class (loneSplit).
//
// Exact integer arithmetic on tones, no floating point in any decision, no random numbers.

import { BlockMap } from '@/code/compute/lab/coarse-block'
import { PairTable, pairIndex } from '@/code/rule/pair-rule'
import { forwardRounds } from '@/code/rule/partitioned-pair'
import { PartitionSchedule } from '@/code/rule/partition-schedule'
import { CosetTiling } from '@/code/substrate/coxeter/coset-tiling'
import { LiftedColoring, liftedColoring, reduceKey } from '@/code/substrate/coxeter/lifted-coloring'

export type Orientation = 'radial' | 'lifted'

export const ORBIT_CAP = 24

// ---- the frame ----

export class TileFrame {
  readonly name: string
  readonly p: number
  readonly q: number
  readonly tiling: CosetTiling
  readonly coloring: LiftedColoring
  readonly orientation: Orientation
  private readonly elementOfTile: number[] = []
  private readonly classOfElement = new Map<number, number>()

  constructor(input: { p: number; q: number; variant: number; orientation: Orientation }) {
    this.p = input.p
    this.q = input.q
    this.tiling = new CosetTiling({ p: input.p, q: input.q })
    this.coloring = liftedColoring(this.tiling, input.variant)
    this.orientation = input.orientation
    this.name = `{${input.p},${input.q}}/v${input.variant}/${input.orientation}`
  }

  // the group element (mod l) of the tile's minimal representative
  elementOf(tile: number): number {
    let g = this.elementOfTile[tile]

    if (g === undefined) {
      g = this.coloring.elementIndex.get(reduceKey(this.tiling.matrix(tile), this.coloring.modulus))

      if (g === undefined) {
        throw new Error(`coarse-tiling: tile ${tile} maps outside the quotient group`)
      }

      this.elementOfTile[tile] = g
    }

    return g
  }

  // the tile's quotient class: the least element index of its coset g H, H generated by s_0 and s_1
  classOf(tile: number): number {
    const g = this.elementOf(tile)
    const hit = this.classOfElement.get(g)

    if (hit !== undefined) {
      return hit
    }

    const l = BigInt(this.coloring.modulus)
    const reduce = (m: bigint[]): bigint[] => m.map(c => ((c % l) + l) % l)
    const start = reduce([...this.tiling.matrix(tile)])
    const seen = new Map<number, bigint[]>([[g, start]])
    const queue = [start]

    for (const m of queue) {
      for (const s of [0, 1]) {
        const x = [...m]

        this.tiling.rightMultiply(x, s)

        const r = reduce(x)
        const h = this.coloring.elementIndex.get(r.join(','))

        if (h === undefined) {
          throw new Error('coarse-tiling: a coset element maps outside the quotient group')
        }

        if (!seen.has(h)) {
          seen.set(h, r)
          queue.push(r)
        }
      }
    }

    if (seen.size !== 2 * this.p) {
      throw new Error(`coarse-tiling: a tile coset has ${seen.size} elements, not ${2 * this.p}`)
    }

    const label = Math.min(...seen.keys())

    for (const h of seen.keys()) {
      this.classOfElement.set(h, label)
    }

    return label
  }

  partner(color: number, tile: number): number {
    return this.tiling.neighbor(tile, this.coloring.slotOfColor[this.elementOf(tile) * this.p + color]!)
  }

  isFirst(color: number, tile: number): boolean {
    const v = this.partner(color, tile)

    if (this.orientation === 'lifted') {
      const a = this.classOf(tile)
      const b = this.classOf(v)

      if (a === b) {
        throw new Error('coarse-tiling: an edge joins two tiles of one quotient class')
      }

      return a < b
    }

    const d = this.tiling.distance(tile) - this.tiling.distance(v)

    return d < 0 || (d === 0 && this.tiling.compare(tile, v) < 0)
  }

  neighbors(tile: number): number[] {
    return Array.from({ length: this.p }, (_, k) => this.tiling.neighbor(tile, k))
  }

  distance(tile: number): number {
    return this.tiling.distance(tile)
  }

  // one tile of every quotient class, in breadth-first order from the origin
  representatives(): number[] {
    const want = this.coloring.quotientTiles
    const found = new Map<number, number>()
    const seen = new Set<number>([0])
    const queue = [0]

    for (const t of queue) {
      const c = this.classOf(t)

      if (!found.has(c)) {
        found.set(c, t)

        if (found.size === want) {
          break
        }
      }

      for (const w of this.neighbors(t)) {
        if (!seen.has(w)) {
          seen.add(w)
          queue.push(w)
        }
      }

      if (queue.length > 400 * want) {
        throw new Error(`coarse-tiling: ${found.size} of ${want} classes found near the origin`)
      }
    }

    if (found.size !== want) {
      throw new Error(`coarse-tiling: ${found.size} of ${want} classes found`)
    }

    return [...found.values()]
  }

  // the tiles within r facets of the origin, in breadth-first order
  ball(r: number): number[] {
    const seen = new Set<number>([0])
    const queue = [0]

    for (const t of queue) {
      if (this.distance(t) >= r) {
        continue
      }

      for (const w of this.neighbors(t)) {
        if (!seen.has(w) && this.distance(w) <= r) {
          seen.add(w)
          queue.push(w)
        }
      }
    }

    return queue
  }
}

// ---- blockings ----

export type Blocking = {
  name: string
  kind: 'edge' | 'orbit'
  // the cells of the block holding a tile, in the block's declared order
  cells(tile: number): number[]
  // a name of the block holding a tile, equal for every tile of it
  key(tile: number): number
}

export function edgeBlocking(frame: TileFrame, color: number): Blocking {
  return {
    name: `E${color}`,
    kind: 'edge',
    cells: t => {
      const v = frame.partner(color, t)

      return frame.isFirst(color, t) ? [t, v] : [v, t]
    },
    key: t => Math.min(t, frame.partner(color, t)),
  }
}

// the orbit of a tile under <M_a, M_b> (alternating), or null when it does not close within cap cells
export function dihedralOrbit(frame: TileFrame, a: number, b: number, tile: number, cap: number): number[] | null {
  const out = [tile]

  let x = tile

  for (let k = 0; ; k++) {
    x = frame.partner(k % 2 === 0 ? a : b, x)

    if (x === tile) {
      return out
    }

    out.push(x)

    if (out.length > cap) {
      return null
    }
  }
}

// D(a, b) when every orbit closes within the cap (checked on one tile per quotient class), else null with the open
// class recorded
export function orbitBlocking(
  frame: TileFrame,
  a: number,
  b: number,
  reps: readonly number[],
): { blocking: Blocking | null; sizes: number[] } {
  const sizes = new Set<number>()

  for (const r of reps) {
    const orbit = dihedralOrbit(frame, a, b, r, ORBIT_CAP)

    if (!orbit) {
      return { blocking: null, sizes: [] }
    }

    sizes.add(orbit.length)
  }

  const cache = new Map<number, number[]>()

  const cells = (t: number): number[] => {
    const hit = cache.get(t)

    if (hit) {
      return hit
    }

    const orbit = dihedralOrbit(frame, a, b, t, ORBIT_CAP)

    if (!orbit) {
      throw new Error(`coarse-tiling: an orbit of D${a}${b} did not close although every class did`)
    }

    const sorted = [...orbit].sort((x, y) => x - y)

    for (const c of orbit) {
      cache.set(c, sorted)
    }

    return sorted
  }

  return {
    blocking: { name: `D${a}${b}`, kind: 'orbit', cells, key: t => cells(t)[0]! },
    sizes: [...sizes].sort((x, y) => x - y),
  }
}

// ---- rules on a background ----

export type LoneMotion = 'mover' | 'static' | 'splits'

export function fixesBackground(table: PairTable, beta: number): boolean {
  const b = pairIndex(beta, beta)

  return table[b] === b
}

// how a lone u on the background beta behaves at a matching (the rule fixing (beta, beta) is the caller's check)
export function loneMotion(table: PairTable, beta: number, u: number): LoneMotion {
  const x = pairIndex(u, beta)
  const y = pairIndex(beta, u)

  if (table[x] === x && table[y] === y) {
    return 'static'
  }

  if (table[x] === y && table[y] === x) {
    return 'mover'
  }

  return 'splits'
}

// P^rounds(tile): the lone mover's track, the round's matchings applied in order
export function motion(frame: TileFrame, colors: readonly number[], tile: number, rounds: number): number {
  let x = tile

  for (let t = 0; t < rounds; t++) {
    for (const color of colors) {
      x = frame.partner(color, x)
    }
  }

  return x
}

export type LoneSplit = { a: number; b: number; imageA: number; imageB: number }

// two cells of one block whose lone-mover images lie in different blocks, searched over the blocks of the given tiles
// (one per quotient class is complete under the lifted coloring); null when P^tau maps every such block onto a block
export function loneSplit(input: {
  frame: TileFrame
  blocking: Blocking
  colors: readonly number[]
  tau: number
  tiles: readonly number[]
}): LoneSplit | null {
  const { frame, blocking, colors, tau, tiles } = input

  for (const r of tiles) {
    const cells = blocking.cells(r)
    const images = cells.map(c => motion(frame, colors, c, tau))
    const keys = images.map(c => blocking.key(c))

    for (let j = 1; j < cells.length; j++) {
      if (keys[j] !== keys[0]) {
        return { a: cells[0]!, b: cells[j]!, imageA: images[0]!, imageB: images[j]! }
      }
    }
  }

  return null
}

// ---- sparse exact runs on the infinite tiling ----

export type Tones = Map<number, number>

export function sparseRounds(input: {
  frame: TileFrame
  table: PairTable
  colors: readonly number[]
  beta: number
  start: Tones
  rounds: number
}): Tones {
  const { frame, table, colors, beta, rounds } = input
  const state = new Map(input.start)
  const get = (c: number): number => state.get(c) ?? beta

  const put = (c: number, v: number): void => {
    if (v === beta) {
      state.delete(c)
    } else {
      state.set(c, v)
    }
  }

  for (let t = 0; t < rounds; t++) {
    for (const color of colors) {
      const done = new Set<number>()

      for (const u of [...state.keys()]) {
        if (done.has(u)) {
          continue
        }

        const v = frame.partner(color, u)

        done.add(u)
        done.add(v)

        const [i, j] = frame.isFirst(color, u) ? [u, v] : [v, u]
        const out = table[(get(i) + 1) * 3 + get(j) + 1]!

        put(i, Math.floor(out / 3) - 1)
        put(j, (out % 3) - 1)
      }
    }
  }

  return state
}

// ---- coarse reading ----

export function blockLetter(input: { blocking: Blocking; map: BlockMap; beta: number; state: Tones; tile: number }): number {
  const { blocking, map, beta, state, tile } = input
  const cells = blocking.cells(tile)

  return map.read(Int8Array.from(cells, c => state.get(c) ?? beta), 0, cells.length)
}

export function backgroundLetter(map: BlockMap, beta: number, size: number): number {
  return map.read(new Int8Array(size).fill(beta), 0, size)
}

// the coarse configuration of a finite-support state: every block whose letter differs from its background letter,
// as 'key:letter' sorted (every other block reads its background letter)
export function coarseKey(input: { blocking: Blocking; map: BlockMap; beta: number; state: Tones }): string {
  const { blocking, map, beta, state } = input
  const out = new Map<number, number>()

  for (const c of state.keys()) {
    const k = blocking.key(c)

    if (out.has(k)) {
      continue
    }

    const letter = blockLetter({ blocking, map, beta, state, tile: c })

    out.set(k, letter === backgroundLetter(map, beta, blocking.cells(c).length) ? Number.NaN : letter)
  }

  return [...out.entries()]
    .filter(([, v]) => !Number.isNaN(v))
    .sort((x, y) => x[0] - y[0])
    .map(([k, v]) => `${k}:${v}`)
    .join(' ')
}

// whether F reads every one-u block (u at any position, every block size in `sizes`) as one letter that differs from
// the background block's letter
export function readsLoneExcitation(map: BlockMap, beta: number, u: number, sizes: readonly number[]): boolean {
  const letters = new Set<number>()

  for (const b of sizes) {
    const t0 = backgroundLetter(map, beta, b)

    for (let k = 0; k < b; k++) {
      const cells = new Int8Array(b).fill(beta)

      cells[k] = u

      const t = map.read(cells, 0, b)

      if (t === t0) {
        return false
      }

      letters.add(t)
    }
  }

  return letters.size === 1
}

// ---- the independent dense path ----

// The tones of `cells` after `rounds` rounds from a finite-support start, by code/rule/partitioned-pair on the exact
// backward dependency set: D_T = cells, D_{k-1} = D_k plus the step-k partners of D_k. A cell of D_k reads its partner
// in D_{k-1}, so every pair it needs lies in the set and its value is exact; nothing outside D_0 reaches `cells`.
export function denseRead(input: {
  frame: TileFrame
  table: PairTable
  colors: readonly number[]
  beta: number
  start: Tones
  rounds: number
  cells: readonly number[]
}): { tones: number[]; size: number } {
  const { frame, table, colors, beta, start, rounds, cells } = input
  const steps = Array.from({ length: rounds }, () => colors).flat()

  let need = new Set(cells)

  for (let k = steps.length - 1; k >= 0; k--) {
    const next = new Set(need)

    for (const x of need) {
      next.add(frame.partner(steps[k]!, x))
    }

    need = next
  }

  const list = [...need]
  const index = new Map(list.map((c, i) => [c, i]))
  const state = Int8Array.from(list, c => start.get(c) ?? beta)
  const matchings = colors.map(color => {
    const flat: number[] = []

    list.forEach((c, i) => {
      const j = index.get(frame.partner(color, c))

      if (j !== undefined && frame.isFirst(color, c)) {
        flat.push(i, j)
      }
    })

    return Int32Array.from(flat)
  })
  const schedule: PartitionSchedule = {
    size: list.length,
    matchings,
    method: 'generator-coloring',
    colorCount: frame.p,
    colorOrder: [...colors],
    orientation: `${frame.orientation} on the dependency set of ${cells.length} cells`,
  }
  const after = forwardRounds({ table, schedule, state, rounds })

  return { tones: cells.map(c => after[index.get(c)!]!), size: list.length }
}

// ---- lumpability witnesses ----

export type TilingWitness = {
  left: [number, number][]
  right: [number, number][]
  coarse: string
  // the block where the coarse futures differ, and its two letters
  block: number
  letters: [number, number]
}

// a witness re-checked: equal coarse starts, and at the named block two different letters by the dense path
export function checkTilingWitness(input: {
  frame: TileFrame
  table: PairTable
  colors: readonly number[]
  beta: number
  tau: number
  blocking: Blocking
  map: BlockMap
  witness: TilingWitness
}): boolean {
  const { frame, table, colors, beta, tau, blocking, map, witness } = input
  const x = new Map(witness.left)
  const y = new Map(witness.right)

  if (coarseKey({ blocking, map, beta, state: x }) !== coarseKey({ blocking, map, beta, state: y })) {
    return false
  }

  const cells = blocking.cells(witness.block)

  const read = (s: Tones): number => {
    const tones = denseRead({ frame, table, colors, beta, start: s, rounds: tau, cells }).tones

    return map.read(Int8Array.from(tones), 0, cells.length)
  }

  return read(x) !== read(y)
}

// the first block (in key order) whose letters differ between two finite-support states
function differingBlock(input: { blocking: Blocking; map: BlockMap; beta: number; x: Tones; y: Tones }): {
  block: number
  letters: [number, number]
} | null {
  const { blocking, map, beta, x, y } = input
  const keys = new Map<number, number>()

  for (const c of [...x.keys(), ...y.keys()]) {
    keys.set(blocking.key(c), c)
  }

  for (const k of [...keys.keys()].sort((a, b) => a - b)) {
    const tile = keys.get(k)!
    const a = blockLetter({ blocking, map, beta, state: x, tile })
    const b = blockLetter({ blocking, map, beta, state: y, tile })

    if (a !== b) {
      return { block: tile, letters: [a, b] }
    }
  }

  return null
}

// The finite-support configurations of the bounded witness search: every state with at most `many` excitations
// (tones other than beta) on `cells`, in a fixed order (fewer excitations first, then cell order, then tones).
export function boundedConfigs(cells: readonly number[], beta: number, many: number): Tones[] {
  const tones = [-1, 0, 1].filter(t => t !== beta)
  const out: Tones[] = []

  const pick = (from: number, chosen: [number, number][]): void => {
    if (chosen.length > 0) {
      out.push(new Map(chosen))
    }

    if (chosen.length === many) {
      return
    }

    for (let i = from; i < cells.length; i++) {
      for (const t of tones) {
        chosen.push([cells[i]!, t])
        pick(i + 1, chosen)
        chosen.pop()
      }
    }
  }

  pick(0, [])

  return out.sort((a, b) => a.size - b.size)
}

// Search the configurations for two with one coarse image and two coarse futures, for each blocking and map. The
// runs are shared: every configuration is evolved once. A witness is a global no-go; none is 'clean' on this set
// only, never a proof of lumpability.
export function witnessSearch(input: {
  frame: TileFrame
  table: PairTable
  colors: readonly number[]
  beta: number
  tau: number
  configs: readonly Tones[]
  readings: readonly { blocking: Blocking; map: BlockMap }[]
}): (TilingWitness | null)[] {
  const { frame, table, colors, beta, tau, configs, readings } = input
  const images = configs.map(start => sparseRounds({ frame, table, colors, beta, start, rounds: tau }))

  return readings.map(({ blocking, map }) => {
    const seen = new Map<string, { image: string; index: number }>()

    for (let i = 0; i < configs.length; i++) {
      const start = coarseKey({ blocking, map, beta, state: configs[i]! })
      const image = coarseKey({ blocking, map, beta, state: images[i]! })
      const prior = seen.get(start)

      if (!prior) {
        seen.set(start, { image, index: i })
        continue
      }

      if (prior.image !== image) {
        const diff = differingBlock({ blocking, map, beta, x: images[prior.index]!, y: images[i]! })

        if (!diff) {
          throw new Error('coarse-tiling: coarse images differ but no block does')
        }

        return {
          left: [...configs[prior.index]!.entries()],
          right: [...configs[i]!.entries()],
          coarse: start,
          block: diff.block,
          letters: diff.letters,
        }
      }
    }

    return null
  })
}

// The lone-mover witness of the theorem for one rule: u at the two cells of a split, on background beta.
export function loneWitness(input: {
  frame: TileFrame
  table: PairTable
  colors: readonly number[]
  beta: number
  u: number
  tau: number
  blocking: Blocking
  map: BlockMap
  split: LoneSplit
}): TilingWitness | null {
  const { frame, table, colors, beta, u, tau, blocking, map, split } = input
  const x = new Map([[split.a, u]])
  const y = new Map([[split.b, u]])
  const ix = sparseRounds({ frame, table, colors, beta, start: x, rounds: tau })
  const iy = sparseRounds({ frame, table, colors, beta, start: y, rounds: tau })
  const diff = differingBlock({ blocking, map, beta, x: ix, y: iy })

  if (!diff || coarseKey({ blocking, map, beta, state: x }) !== coarseKey({ blocking, map, beta, state: y })) {
    return null
  }

  return {
    left: [...x.entries()],
    right: [...y.entries()],
    coarse: coarseKey({ blocking, map, beta, state: x }),
    block: diff.block,
    letters: diff.letters,
  }
}
