// THE VALUE PHASE (item vibe-roadmap-grounding-0005, grounding decision 001, board decision 002): an opt-in rule piece
// that tells a love (+1) from a fear (-1), added to the working rule (code/rule/coined-locked-knit coinedVetoBeat, the
// coin, then the no-veto beat). With the piece off the beat is coinedVetoBeat, bit for bit.
//
// THE PIECE. A diagonal phase on each branch of the superposed state: W = zeta6^n, zeta6 = 1 + w (a unit of Z[w], a
// primitive sixth root of unity, zeta6^2 = w), so every amplitude stays in Z[w][1/2], inside the model ring Z[w][1/6].
// Its inverse is zeta6^-n = (-w)^n. The exponent is n = sum over docks x of sigma(x) chi(x): chi reads only the dock's
// own slot tones (vibe trits, open or closed; no point, no store), and sigma(x) is the dock's orientation (+1 when the
// piece is label-written). The empty mesh has n = 0, so the vacuum has no valence (key 5).
//
// WHERE IN THE BEAT. Palindromically around the dock-local block X (coin, meeting, collision): stream, then W, X, W.
// One beat is U = S W X W. For the motion reversal T = K S R (code/measure/locked-parity motionReversal) this is the
// order that makes a T-even exponent (one R leaves invariant) T-even as a piece: T U T^-1 = W^-1 X^-1 W^-1 S^-1 = U^-1
// whenever T X T^-1 alone does (T S T^-1 = S^-1, T X T^-1 = S X^-1 S^-1, T W T^-1 = S W^-1 S^-1). Built as
// (S W S^-1) coinedVetoBeat(W psi): the second W is read on each configuration with its stream undone, which is the
// configuration before the stream.
//
// THE THREE READINGS chi, all C-odd (chi(-s) = -chi(s)):
//   'even'      the tone of every full like line of the dock (+1 for two loves, -1 for two fears). Invariant under all
//               of W(F4), so mirror-even; two-body. sigma = 1.
//   'odd'       a W(F4) pseudoscalar: the sum over every k*-subset U of the dock's occupied slots of eps(U), the census
//               sign below; sigma = the dock's orientation (a mesh's 2-colouring). Mirror-odd, and zero on every dock
//               holding fewer than k* vibes.
//   'oddLabel'  the same chi with sigma = 1: written in slot labels, the control (on the honeycomb a label-written
//               mirror-odd piece alternates hand dock by dock, E-FRC-0272, E-FRC-0274).
//
// THE CENSUS (fixed in the item's what before this file existed). W(F4) as permutations of the 24 slots, generated by
// the reflections in the 48 F4 roots, det = the parity of a reflection word. A pattern is a set of k vibes with tones
// on distinct slots, coded as the sorted codes 2 slot + (tone < 0). The group G = {+1, -1} x W(F4) acts by (c, g) U =
// {(g s, c t)}. A pattern qualifies when every (c, g) with c g U = U has c det(g) = +1 (no mirror and no charge
// conjugation-rotation fixes it with the wrong sign). k* is the least k with a qualifying pattern. Patterns are visited
// in lexicographic order of their sorted codes; each qualifying class's first member gets eps = +1, and eps(c g U) =
// c det(g) eps(U); every other pattern has eps = 0.
//
// NOTHING MOVES: the piece multiplies amplitudes; the configurations are the rule's own.

