const SLOTS = 24
const LINE_SECONDS: readonly number[] = LINE_FIRSTS.map(f => OPPOSITE[f]!)
const MAX_K = 5

export type ValueKind = 'off' | 'even' | 'odd' | 'oddLabel'

export const VALUE_KINDS: readonly ValueKind[] = [
  'off',
  'even',
  'odd',
  'oddLabel',
]

export type ValuePiece = {
  readonly kind: ValueKind
  // per dock +1 or -1, read by 'odd' only (undefined: +1 everywhere, as on the flat box)
  readonly orientation?: Int8Array
}

// ---- W(F4) as slot permutations ----

export type SlotGroup = {
  // every element as a slot permutation, breadth-first from the identity over the 48 root reflections
  readonly elements: readonly Int8Array[]
  // +1 or -1
  readonly det: readonly number[]
  // the 48 generating reflections (one per F4 root, in rootsF4 order)
  readonly reflections: readonly Int8Array[]
}

let groupMemo: SlotGroup | undefined

export function slotGroup(): SlotGroup {
  if (groupMemo) {
    return groupMemo
  }

  const reflections = rootsF4().map(r => {
    const rr = r.reduce((s, v) => s + v * v, 0)
    const matrix = [0, 1, 2, 3].map(i =>
      [0, 1, 2, 3].map(j => (i === j ? 1 : 0) - (2 * r[i]! * r[j]!) / rr),
    )
    const p = slotPermutationOf(matrix)

    if (!p) {
      throw new Error('value-phase: an F4 root reflection does not permute the slots')
    }

    return Int8Array.from(p)
  })
  const identity = Int8Array.from({ length: SLOTS }, (_, d) => d)
  const elements: Int8Array[] = [identity]
  const det: number[] = [1]
  const seen = new Map<string, number>([[identity.join(','), 0]])

  for (let head = 0; head < elements.length; head++) {
    const e = elements[head]!

    for (const r of reflections) {
      const next = Int8Array.from({ length: SLOTS }, (_, d) => r[e[d]!]!)
      const key = next.join(',')
      const known = seen.get(key)

      if (known === undefined) {
        seen.set(key, elements.length)
        elements.push(next)
        det.push(-det[head]!)
      } else if (det[known] !== -det[head]!) {
        throw new Error('value-phase: the reflection-word parity is not a determinant')
      }
    }
  }

  groupMemo = { elements, det, reflections }

  return groupMemo
}

// ---- the census ----

export type Census = {
  // k* (the least size with a qualifying pattern), or 0 when none up to MAX_K
  readonly kStar: number
  // classes and qualifying classes of each size 1..kStar (index k - 1)
  readonly classes: readonly number[]
  readonly qualifying: readonly number[]
  // the first qualifying pattern, as [slot, tone] pairs
  readonly first: readonly (readonly [number, number])[]
  // eps of every size-kStar pattern with eps != 0, keyed by patternKey
  readonly eps: ReadonlyMap<number, number>
}

const BASE = 2 * SLOTS

// a pattern's key from its codes in increasing order
export function patternKey(codes: readonly number[]): number {
  let key = 0

  for (let i = codes.length - 1; i >= 0; i--) {
    key = key * BASE + codes[i]!
  }

  return key
}

let censusMemo: Census | undefined

export function valueCensus(): Census {
  if (censusMemo) {
    return censusMemo
  }

  const g = slotGroup()
  const classes: number[] = []
  const qualifying: number[] = []

  for (let k = 1; k <= MAX_K; k++) {
    const eps = new Map<number, number>()
    const visited = new Set<number>()

    let classCount = 0
    let qualifyingCount = 0
    let first: [number, number][] | undefined

    // codes in increasing order with distinct slots: lexicographic order of the sorted codes
    const codes: number[] = []
    const image: number[] = new Array<number>(k).fill(0)

    const visit = (): void => {
      const key = patternKey(codes)

      if (visited.has(key)) {
        return
      }

      classCount++

      const signs = new Map<number, number>()

      let ok = true

      for (let e = 0; e < g.elements.length; e++) {
        const p = g.elements[e]!

        for (const c of [1, -1]) {
          for (let i = 0; i < k; i++) {
            const slot = codes[i]! >> 1
            const tone = codes[i]! & 1 ? -1 : 1

            image[i] = 2 * p[slot]! + (c * tone < 0 ? 1 : 0)
          }

          const sorted = [...image].sort((a, b) => a - b)
          const ik = patternKey(sorted)
          const s = c * g.det[e]!
          const known = signs.get(ik)

          if (known === undefined) {
            signs.set(ik, s)
          } else if (known !== s) {
            ok = false
          }
        }
      }

      for (const ik of signs.keys()) {
        visited.add(ik)
      }

      if (ok) {
        qualifyingCount++

        for (const [ik, s] of signs) {
          eps.set(ik, s)
        }

        first ??= codes.map(c => [c >> 1, c & 1 ? -1 : 1])
      }
    }

    const recurse = (from: number, usedSlots: number): void => {
      if (codes.length === k) {
        visit()

        return
      }

      for (let c = from; c < BASE; c++) {
        const slot = c >> 1

        if ((usedSlots >> slot) & 1) {
          continue
        }

        codes.push(c)
        recurse(c + 1, usedSlots | (1 << slot))
        codes.pop()
      }
    }

    recurse(0, 0)
    classes.push(classCount)
    qualifying.push(qualifyingCount)

    if (qualifyingCount > 0) {
      censusMemo = { kStar: k, classes, qualifying, first: first!, eps }

      return censusMemo
    }
  }

  censusMemo = { kStar: 0, classes, qualifying, first: [], eps: new Map() }

  return censusMemo
}

// ---- the readings ----

// chi of one dock given its occupied slots (increasing) and their tones
function chiOf(
  kind: ValueKind,
  slots: readonly number[],
  tones: readonly number[],
  dockVibe: (d: number) => number,
): number {
  if (kind === 'even') {
    let n = 0

    for (let l = 0; l < 12; l++) {
      const a = dockVibe(LINE_FIRSTS[l]!)

      if (a !== 0 && a === dockVibe(LINE_SECONDS[l]!)) {
        n += a
      }
    }

    return n
  }

  const census = valueCensus()
  const k = census.kStar

  if (k === 0 || slots.length < k) {
    return 0
  }

  const codes = slots.map((s, i) => 2 * s + (tones[i]! < 0 ? 1 : 0))
  const pick: number[] = []

  let n = 0

  const recurse = (from: number): void => {
    if (pick.length === k) {
      n += census.eps.get(patternKey(pick)) ?? 0

      return
    }

    for (let i = from; i <= codes.length - (k - pick.length); i++) {
      pick.push(codes[i]!)
      recurse(i + 1)
      pick.pop()
    }
  }

  recurse(0)

  return n
}

// the exponent n of a configuration; `unstream` reads it with the stream undone (each vibe at its source slot)
export function valueExponent(
  piece: ValuePiece,
  tables: LockedTables,
  c: Configuration,
  unstream = false,
): number {
  if (piece.kind === 'off') {
    return 0
  }

  // the occupied slots, by dock
  const byDock = new Map<number, [number, number][]>()

  for (let i = 0; i < c.vibe.length; i++) {
    const v = c.vibe[i]!

    if (v === 0) {
      continue
    }

    const at = unstream ? tables.source[i]! : i
    const x = (at / SLOTS) | 0
    const list = byDock.get(x)

    if (list) {
      list.push([at % SLOTS, v])
    } else {
      byDock.set(x, [[at % SLOTS, v]])
    }
  }

  let n = 0

  for (const [x, list] of byDock) {
    list.sort((p, q) => p[0] - q[0])

    const tone = new Int8Array(SLOTS)

    for (const [d, v] of list) {
      tone[d] = v
    }

    const chi = chiOf(
      piece.kind,
      list.map(p => p[0]),
      list.map(p => p[1]),
      d => tone[d]!,
    )
    const sigma =
      piece.kind === 'odd' && piece.orientation ? piece.orientation[x]! : 1

    n += sigma * chi
  }

  return n
}

export type ValueTally = {
  // W applications with n != 0 (per branch), and the largest |n|
  fired: number
  maxExponent: number
}

export const newValueTally = (): ValueTally => ({ fired: 0, maxExponent: 0 })

// zeta6^n on a branch (n any integer); inverse: zeta6^-n
function phase(br: Branch, n: number, inverse: boolean): void {
  const m = ((((inverse ? -n : n) % 6) + 6) % 6)

  for (let i = 0; i < m; i++) {
    times(br, 1n, 1n)
  }
}

function applyHalf(
  piece: ValuePiece,
  tables: LockedTables,
  s: LockedState,
  unstream: boolean,
  inverse: boolean,
  tally?: ValueTally,
): LockedState {
  for (const br of s.branches) {
    const n = valueExponent(piece, tables, br, unstream)

    if (n !== 0 && tally) {
      tally.fired++
      tally.maxExponent = Math.max(tally.maxExponent, Math.abs(n))
    }

    phase(br, n, inverse)
  }

  return s
}

const cloneState = (s: LockedState): LockedState => ({
  branches: s.branches.map(b => ({
    vibe: Int8Array.from(b.vibe),
    point: Int8Array.from(b.point),
    open: Uint8Array.from(b.open),
    store: Int8Array.from(b.store),
    spoint: Int8Array.from(b.spoint),
    sopen: Uint8Array.from(b.sopen),
    a: b.a,
    b: b.b,
    k: b.k,
  })),
})

// one beat of the working rule with the value phase: U = S W X W
export function valueBeat(
  piece: ValuePiece,
  tables: LockedTables,
  s: LockedState,
  beat: number,
  tally?: LockedTally,
  valueTally?: ValueTally,
): LockedState {
  if (piece.kind === 'off') {
    return coinedVetoBeat('none', tables, s, beat, tally)
  }

  const first = applyHalf(piece, tables, cloneState(s), false, false, valueTally)
  const mid = coinedVetoBeat('none', tables, first, beat, tally)

  return applyHalf(piece, tables, mid, true, false, valueTally)
}

// its exact inverse: U^-1 = W^-1 X^-1 W^-1 S^-1
export function valueBeatBack(
  piece: ValuePiece,
  tables: LockedTables,
  s: LockedState,
  beat: number,
): LockedState {
  if (piece.kind === 'off') {
    return coinedVetoBeatBack('none', tables, s, beat)
  }

  const first = applyHalf(piece, tables, cloneState(s), true, true)
  const mid = coinedVetoBeatBack('none', tables, first, beat)

  return applyHalf(piece, tables, mid, false, true)
}
