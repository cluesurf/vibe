// P51: the full integer ladder in one program.
// The integer-ladder analysis describes a tower: from the integers Z, generate a group by
// its automaton, emit the tessellation, and run the model on it, so the whole thing from
// the integers to the lived substrate is one continuous construction. This builds that
// tower end to end, for both the parameter-free modular group and a chosen Coxeter
// crystal {7,3}, through the SAME pipeline:
//   Rung 0  integers Z (the generator data)
//   Rung 1+6  the group, grown deterministically by its automaton (no randomness)
//   Rung 3+4  the tessellation, emitted and embedded
//   Rung 5  the vibe model, run on it (ternary rule, Lorentz-safe, determined)
// See the integer-ladder analysis. Run: npx tsx code/experiment/p51-full-ladder.ts

import { pathToFileURL } from 'node:url'
import { makeRng } from '~/core/rng'
import { modularGraph } from '~/experiment/p48-modular-base'
import { coxeterTessellation } from '~/substrate/coxeter'
import { Graph } from '~/core/graph'
import { lorentzIsotropy } from '~/measure/lorentz'

// Run the committed vibe rule (ternary signed-majority, symmetric fills) on a substrate,
// the top rung. Returns whether it is reproducible (determined) and that it evolves
// (the model actually runs, not a trivial fixed point from the start).
function runModel(g: Graph, seed: number): { deterministic: boolean; evolves: boolean; nonzeroFraction: number } {
  const rng = makeRng({ seed })
  const indexOf = g.neighbors.map((row) => {
    const m = new Map<number, number>()
    for (let k = 0; k < row.length; k++) {
      m.set(row[k] ?? -1, k)
    }
    return m
  })
  const fills = g.neighbors.map((row) => new Int8Array(row.length))
  for (let v = 0; v < g.size; v++) {
    const fv = fills[v]
    const row = g.neighbors[v] ?? new Uint32Array(0)
    if (!fv) {
      continue
    }
    for (let k = 0; k < row.length; k++) {
      const w = row[k] ?? 0
      if (w > v) {
        const f = rng.nextInt({ max: 3 }) - 1
        fv[k] = f
        const fw = fills[w]
        const kk = indexOf[w]?.get(v)
        if (fw && kk !== undefined) {
          fw[kk] = f
        }
      }
    }
  }
  const init = new Int8Array(g.size)
  for (let i = 0; i < g.size; i++) {
    init[i] = rng.nextInt({ max: 3 }) - 1
  }
  const run = (): Int8Array => {
    let tone = Int8Array.from(init)
    for (let b = 0; b < 30; b++) {
      const next = new Int8Array(g.size)
      for (let v = 0; v < g.size; v++) {
        const nb = g.neighbors[v] ?? new Uint32Array(0)
        const fl = fills[v] ?? new Int8Array(0)
        let h = 0
        for (let k = 0; k < nb.length; k++) {
          h += (fl[k] ?? 0) * (tone[nb[k] ?? 0] ?? 0)
        }
        next[v] = h > 0 ? 1 : h < 0 ? -1 : 0
      }
      tone = next
    }
    return tone
  }
  const a = run()
  const b = run()
  let deterministic = true
  let evolves = false
  let nonzero = 0
  for (let i = 0; i < g.size; i++) {
    if (a[i] !== b[i]) {
      deterministic = false
    }
    if (a[i] !== init[i]) {
      evolves = true
    }
    if (a[i] !== 0) {
      nonzero++
    }
  }
  return { deterministic, evolves, nonzeroFraction: nonzero / g.size }
}

export function fullLadder(input: { base: 'modular' | number[]; seed: number }): {
  name: string
  fromIntegers: boolean
  size: number
  anisotropy: number
  lorentzSafe: boolean
  modelDeterministic: boolean
  modelEvolves: boolean
} {
  let g: Graph
  let name: string
  if (input.base === 'modular') {
    g = modularGraph(1800)
    name = 'modular group PSL(2,Z)'
  } else {
    g = coxeterTessellation({ schlafli: input.base, maxVertices: 1500 })
    name = `Coxeter crystal {${input.base.join(',')}}`
  }
  const aniso = lorentzIsotropy({ substrate: g, samples: 3000, rng: makeRng({ seed: input.seed }) })
  const model = runModel(g, input.seed + 1)
  return {
    name,
    fromIntegers: true, // both are generated by integer-matrix / reflection automata, no rng
    size: g.size,
    anisotropy: aniso.anisotropy,
    lorentzSafe: aniso.anisotropy < 0.25,
    modelDeterministic: model.deterministic,
    modelEvolves: model.evolves,
  }
}

export function main(): void {
  console.log('P51: the full integer ladder in one program')
  console.log('')
  console.log('  Rung 0: the integers Z (generator matrices and Schlafli symbols)')
  console.log('  Rung 1+6: the group, grown deterministically by its automaton, no randomness')
  console.log('  Rung 3+4: the tessellation, emitted and embedded')
  console.log('  Rung 5: the vibe model, run on it')
  console.log('')
  for (const base of ['modular', [7, 3], [5, 4]] as ('modular' | number[])[]) {
    const r = fullLadder({ base, seed: 2 })
    console.log(`  ${r.name}:`)
    console.log(`    from the integers, no randomness in generation: ${r.fromIntegers ? 'YES' : 'no'}`)
    console.log(`    tessellation of ${r.size} cells, Lorentz anisotropy ${r.anisotropy.toFixed(3)}, Lorentz-safe ${r.lorentzSafe ? 'YES' : 'no'}`)
    console.log(`    model runs on it, reproducible ${r.modelDeterministic ? 'YES' : 'no'}, evolves ${r.modelEvolves ? 'YES' : 'no'}`)
    console.log('')
  }
  console.log('  The whole tower stands as one construction. From integer generator data, a')
  console.log('  deterministic automaton grows the group and emits the tessellation, and the vibe')
  console.log('  rule runs on the result, Lorentz-safe and reproducible. The modular group (the')
  console.log('  parameter-free base) and the {7,3} and {5,4} crystals all come through the same')
  console.log('  pipeline, integers to lived substrate, with nothing arbitrary and no randomness in')
  console.log('  the generation. This is the canonical base, built end to end.')
}

if (
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main()
}
