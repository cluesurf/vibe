// P51: the full integer ladder in one program.
// The integer-ladder analysis describes a tower: from the integers Z, generate a group by
// its automaton, emit the tessellation, and run the model on it, so the whole thing from
// the integers to the lived substrate is one continuous construction. This builds that
// tower end to end, for both the parameter-free modular group and a chosen Coxeter
// crystal {7,3}, through the SAME pipeline:
//   Rung 0  integers Z (the generator data)
//   Rung 1+6  the group, grown deterministically by its automaton (no randomness)
//   Rung 3+4  the tessellation, emitted and embedded
//   Rung 5  the vibe model, run on it (ternary rule, Lorentz-safe, determined)
// See the integer-ladder analysis. Run: npx tsx code/experiment/p51-full-ladder.ts

import { makeRng } from '@/code/tool/rng'
import { modularGraph } from '@/code/substrate/modular-group'
import { coxeterTessellation } from '@/code/substrate/coxeter'
import { Graph } from '@/code/tool/graph'
import { lorentzIsotropy } from '@/code/measure/lorentz'
import { runModel } from '@/code/compute/run-model'
import { experiment } from '@/test/scaffold/suite'
import { verdict } from '@/test/scaffold/verdict'

export function fullLadder(input: {
  base: 'modular' | number[]
  seed: number
}): {
  name: string
  fromIntegers: boolean
  size: number
  anisotropy: number
  lorentzSafe: boolean
  modelDeterministic: boolean
  modelEvolves: boolean
} {
  let g: Graph
  let name: string
  if (input.base === 'modular') {
    g = modularGraph(1800)
    name = 'modular group PSL(2,Z)'
  } else {
    g = coxeterTessellation({ schlafli: input.base, maxVertices: 1500 })
    name = `Coxeter crystal {${input.base.join(',')}}`
  }
  const aniso = lorentzIsotropy({
    substrate: g,
    samples: 3000,
    rng: makeRng({ seed: input.seed }),
  })
  const model = runModel(g, input.seed + 1)
  return {
    name,
    fromIntegers: true, // both are generated by integer-matrix / reflection automata, no rng
    size: g.size,
    anisotropy: aniso.anisotropy,
    lorentzSafe: aniso.anisotropy < 0.25,
    modelDeterministic: model.deterministic,
    modelEvolves: model.evolves,
  }
}

export default experiment({
  id: 'substrate-survey/full-ladder',
  title:
    'from integer generator data a deterministic automaton grows a Lorentz-safe substrate the model runs on',
  category: 'substrate-survey',
  substrates: 'any',
  depth: 'L2',
  paper: true,
  run() {
    const mod = fullLadder({ base: 'modular', seed: 2 })
    const hept = fullLadder({ base: [7, 3], seed: 2 })
    const ok =
      mod.fromIntegers &&
      mod.lorentzSafe &&
      mod.modelDeterministic &&
      mod.modelEvolves &&
      hept.fromIntegers &&
      hept.lorentzSafe &&
      hept.modelDeterministic &&
      hept.modelEvolves
    return verdict({
      status: ok ? 'pass' : 'fail',
      claim:
        'integers grow a group and tessellation by a deterministic automaton and the vibe model runs on it Lorentz-safe and reproducible for both the modular and {7,3} bases',
      metrics: {
        modularAnisotropy: mod.anisotropy,
        heptagridAnisotropy: hept.anisotropy,
      },
    })
  },
})
