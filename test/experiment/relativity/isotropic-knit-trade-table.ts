// The trade table of the isotropic knits: which symmetry group buys which transport law, and what each
// candidate keeps (E-RLT-0063).
//
// THE QUESTION. E-RLT-0061 built a knit with W(F4) as its exact symmetry and E-RLT-0062 asked whether a
// schedule of conjugates could stand in for one. This experiment asks what is the least symmetry that buys
// the k^4 law, builds the candidates the theorems still allow, and measures every one against the same list
// of properties, so the choice can be read off one table.
//
// 1. THE LEAST GROUP (code/measure/isotropy-group-census). Every subgroup of W(F4) generated by two elements
//    (one from each conjugacy class and any other), up to order 192: whether its invariants restricted to the
//    husk force the scalar transport (diffusion, sound) through degree 4, and, for those that do, the husk
//    shear at its leading degree, the degree-6 scalars, whether it acts freely on the 24 slots, and how many
//    line-momentum forms exact local color would freeze (E-RLT-0051).
// 2. THE CANDIDATES, each a period-one coin-map knit that keeps charge, count and momentum and is an
//    involution (so CPT holds by the argument of E-RLT-0061), built in code/rule/isometric-knit:
//    - isometric: W(F4)-covariant (E-RLT-0061)
//    - color-exact: the isometric knit applied only where it keeps all twelve line momenta, so the side sum
//      and exact local color are kept; E-RLT-0051 says that under W(F4) this is the only way to keep color
//    - binary-tetrahedral: covariant under the least forcing group of part 1 only (2T by left quaternion
//      multiplication), the first-mirror choice carried around each free orbit of momenta
//    - first-mirror: covariant under nothing but {I, -I} (the control)
//    For each: the exact linearization (code/measure/line-momentum-linearization), its commutation with W(F4)
//    and with 2T, the ledger over 1,152 coin maps and 6 vibe maps (glides, parity, CPT), the rule's stabilizer
//    (exhaustive, for the rules that read P alone), the dock audit (involution, charge, count, P, side sum,
//    line momenta, slots touched, on every lone and two-vibe dock and 20,000 Kronecker docks), the line pairs
//    the collision couples, the husk transport exponents and coefficients (E-RLT-0059's ladder), and the
//    E-FRC-0125 acceptance battery (reversal, CPT phase, vacuum period, line-graph components, superposition,
//    walls, dressing, travel, code/measure/weave-acceptance).
// 3. THE TABLE. The four computed rows beside the rows already measured elsewhere: the committed and combined
//    knits (E-RLT-0059), the quaternion knit (E-RLT-0051, E-RLT-0054), the orbit knit (E-RLT-0048), the
//    palindromic schedule (E-RLT-0062), the W(F4)-averaged matrix (E-RLT-0059, E-RLT-0061).
//
// Gates, fixed before the first run (a probe, tmp/iso-census-probe.ts, had run the census to order 48 and
// found the least order 24, one class, free, not forcing the shear; the knits' exponents other than the
// isometric knit's and the first-mirror control's had not been computed):
//  X1 exactness: every candidate 0 involution, charge, count and P failures on the audit docks; the
//     isometric and color-exact matrices commute with all 1,152 coin maps to 1e-12, the binary-tetrahedral
//     matrix with the 24 of 2T to 1e-12 and the first-mirror matrix with 2T not (defect over 1e-3); the
//     color-exact knit changes the side sum and the line momenta on 0 docks; every candidate touches all 24
//     slots
//  X2 invariants: 6 (charge, count, P) for the isometric, binary-tetrahedral and first-mirror knits, 14 (the
//     12 line momenta, charge, count) for the color-exact knit, each with as many unit eigenvalues of M(0)
//  X3 census: the least order forcing the husk scalars through degree 4 is 24, and every group of that order
//     that does acts freely on the slots; every husk fit gated below resolved (standard error under 0.3)
// HYPOTHESES (predictions from part 1 and E-RLT-0058, written before the knits were read):
//  H1 the binary-tetrahedral knit gets the scalar law from 2T alone: husk charge, trace and sound exponents
//     at least 3.5, and its husk shear exponent under 1 (2T does not force the shear at leading order)
//  H2 exact local color does not cost the scalar law: the color-exact knit's husk charge and trace exponents
//     are at least 3.5
// Verdict: pass if X1 to X3, H1 and H2 hold; fail if X1 to X3 hold and a hypothesis does not; partial
// otherwise.
//
// DETERMINISM: exhaustive group theory, exact counts, Kronecker test states. Depth L2.

