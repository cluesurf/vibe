// Can a vacuum whose pairs visit every dock keep isotropic husk transport? (E-RLT-0094)
//
// THE QUESTION. E-RLT-0093's coset-union vacuum fills every dock of the hub pattern's empty classes. The hub vacuum's
// husk transport is isotropic because its oriented store is kept by 576 elements of W(F4), which force the husk scalars
// (charge, trace, sound) through k^4 and the shear at leading order (E-RLT-0080, 0086). What does filling cost?
//
// THE OBSTRUCTION, stated before the run. An affine symmetry (g, t, c) that fixes a dock fixes that dock's stored
// lines as a set, and keeps a stored unit only if it maps its oriented root r to c r (to itself, times the charge
// sign). The hub pattern stores one line per root dock, so the stabilizer of a dock may act on it by +-1 freely. A
// covering pattern stores two or more lines of one triality frame on a root dock (E-RLT-0093: the line toward class 0
// and the lines toward the norm-4 hubs), and an element fixing two of them must act on BOTH by the same sign c. The
// census below measures what that removes.
//
// THE CENSUS (code/measure/union-orientation), exact:
//  (a) every subgroup of W(F4) generated by two elements; those forcing the husk scalars and the shear; the minimal
//      ones; and every subgroup generated by three elements that forces, checked to contain a forcing two-generated one
//  (b) the union (four lines per root dock) is W(F4)-invariant and L'-periodic as an unoriented pattern, so every
//      affine symmetry with linear part g is x -> g x + t with t in L' mod 4 D4 (64 on the side-4 cell) and c = +-1. A
//      group keeping an orientation keeps it with the lifts of its generators; so a minimal forcing group none of whose
//      lift pairs keeps an orientation shows that NO orientation of the union is kept by any forcing group containing it
//  (c) the 2T-equivariant covering patterns with two lines per root dock (the hub line and one norm-4 line) and three:
//      the set O of elements with an orientation-keeping lift, every subgroup inside O (a kept group lies inside O),
//      and their forcing
//
// THE MEASUREMENT. The exact periodic husk transport of the oriented union (E-RLT-0093's candidate, kept by 72
// elements, which force the scalars and not the shear) under L, read by E-RLT-0086's symmetry-adapted reader on the
// side-4 cell: 18 closed-form invariants, the Bloch effective operator, 16 husk directions, rungs kc / 4 and kc / 16
// with E-RLT-0085's kc. Every dock's collision matrices are the exact linearization of its stored row, one per W(F4)
// orbit of rows, carried by the covariance (code/measure/dense-hub multiLineDockMatrices, checked here against
// bounce-transport's dockMatrices on the hub store).
//
// Gates, fixed before this file's first run (probes tmp/dense-probe3 to dense-probe8 ran the census and the reader's
// set-up first, disclosed):
//  S0 the instruments: the hub pattern's 576 group forces the scalars and the shear and keeps the hub orientation
//     (orientUnits, 0 conflicts); the multi-line matrices equal dockMatrices on the hub store to 1e-12
//  S1 the theorem: the forcing two-generated subgroups all contain one minimal group, every forcing three-generated
//     subgroup contains a forcing two-generated one, and no lift pair of the minimal group's generators keeps an
//     orientation of the union; the two- and three-line covering patterns have no forcing subgroup inside O
//  T  the target (2) on the oriented union: the reader's invariants hold on the medium (left residual below 1e-9),
//     and the charge, trace and sound exponents are at least 3.5 and the shear 2 +- 0.5 (E-RLT-0086's gate)
// Verdict: pass if S0, S1 and T; fail if S0 and S1 hold and T fails (the prediction: the shear is not forced, so it
// is expected to read near 0, the scalars near 4); partial if S0 or S1 fails.
//
// FIRST RUN (694 s, tmp/rlt094-run1.log): PASS, against the stated prediction for T, no gate moved. S0 holds (the
// hub's 576 forces all three and keeps an orientation with 0 conflicts; carrier error 4.1e-14). S1 holds: 1,790
// two-generated subgroups (25 classes), 4 force the scalars and shear (orders 576, 576, 1,152, 288, all normal), the
// one minimal is the normal subgroup of order 288, and all 4,778 three-generated subgroups (2,025,791 closures) that
// force contain it; 0 of its 16,384 lift pairs keep an orientation of the union; the two- and three-line covering
// patterns have 192 and 168 elements in O and 405 and 310 subgroups inside, 10 and 8 forcing the scalars, 0 the
// shear. T holds, which was NOT predicted: the oriented union's exact periodic transport reads charge 3.99, trace
// 4.14, sound 4.04, shear 2.03 (anisotropy 5.8e-3 then 3.5e-4 at kc / 4 and kc / 16), the invariants kept to 1.5e-12,
// the physical-staggered coupling 3e-12 (the hub's was 0.05 to 0.08 k^2). So the store's own group is a sufficient
// reason for isotropy, not a necessary one: the shear is isotropic at leading order although no group the ORIENTED
// store keeps forces it. A probe after this run (tmp/dense-probe9) found the linear medium commutes with exactly the
// same 72 elements about the hub (defect 1.1e-13 kept, at least 0.33 for every other), so the extra isotropy does
// not come from a larger point group about the hub; affine elements with an L' translation were not tested, and the
// cause (a hidden affine symmetry, or the four independent parts averaging) is OPEN. The physical-staggered coupling
// of 3e-12 against the hub's 0.05 k^2 points at an exact reason. Title written after the run.
//
// DETERMINISM: exact enumeration; the reader's start block and directions are E-RLT-0086's, no draw. Depth L2. Husk
// first: every direction has k4 = 0.

import { experiment } from '@/test/scaffold/suite'
import { verdict } from '@/test/scaffold/verdict'
import { makeColorWeave } from '@/code/rule/color-weave'
import { dockMatrices, periodicMedium } from '@/code/measure/bounce-transport'
import { binaryTetrahedralIndices, boxMaps, huskForcing, orientedHub, orientedHubStore, pointGenerator } from '@/code/measure/varying-vacuum'
import { cellOps, leftInvariants, leftResidual, namedDockInvariants, readSymmetricTransport, rightInvariants, type SymmetricReading } from '@/code/measure/symmetry-transport'
import { huskDirections } from '@/code/measure/husk-transport-order'
import { classKinds, classOf, coinsOnce, heldOf, multiLineDockMatrices, orientedUnion, orientedUnionStore, orientUnits, unionHubStore } from '@/code/measure/dense-hub'
import { coveringPattern, forcingCensus, insideSubgroups, NORM4_KEYS, orientingLiftPairs } from '@/code/measure/union-orientation'

const KC = 0.2793069366894861
const RUNGS = [KC / 4, KC / 16]

export default experiment({
  id: 'relativity/covering-vacuum-isotropy',
  code: 'E-RLT-0094',
  title:
    "isotropy of a covering vacuum, pass (the transport half against its prediction): no orientation of the coset-union store is kept by a group forcing the husk shear (every forcing subgroup of W(F4) generated by at most three elements contains one normal subgroup of order 288, and 0 of its 16,384 lift pairs keep an orientation; the two- and three-line covering patterns have 0 shear-forcing subgroups inside their orientable sets), because a symmetry fixing two stored lines of one frame must act on both by the same charge sign; yet the exact periodic husk transport of the oriented union (72 kept) reads charge 3.99, trace 4.14, sound 4.04 and shear 2.03, with the physical and staggered invariants uncoupled to 3e-12: the store's group is sufficient for isotropy, not necessary",
  category: 'relativity',
  substrates: ['3434'],
  depth: 'L2',
  paper: false,
  run() {
    const started = Date.now()
    const log = (what: string): void => console.error(`${what} ${Math.round((Date.now() - started) / 1000)}s`)
    const coins = coinsOnce()
    const table = coins.table
    const box = boxMaps(coins, 4)
    const hub = orientedHub(coins)
    const hubForcing = huskForcing(coins, hub.group)
    const hubHeld = heldOf(orientedHubStore(coins, 4, [0, 0, 0, 0]))
    const hubOriented = orientUnits(hubHeld, [...hub.twoT, hub.extra].map(g => pointGenerator(coins, box, g, [0, 0, 0, 0], 1)))
    const hubStore = orientedHubStore(coins, 4, [0, 0, 0, 0])
    const mine = multiLineDockMatrices('lone', hubStore, 256, coins)
    const theirs = dockMatrices({ kind: 'lone', store: hubStore, cells: 256, permutations: table.permutations })
    let carrierError = 0

    for (let x = 0; x < 256; x++) {
      const a = mine.even[x] as Float64Array
      const b = theirs.even[x] as Float64Array
      const c = mine.odd[x] as Float64Array
      const d = theirs.odd[x] as Float64Array

      for (let i = 0; i < a.length; i++) carrierError = Math.max(carrierError, Math.abs((a[i] as number) - (b[i] as number)), Math.abs((c[i] as number) - (d[i] as number)))
    }

    const s0 = hubForcing.husk2 && hubForcing.husk4 && hubForcing.huskShear2 && hubOriented.ok && carrierError < 1e-12

    log('S0')

    // ---- S1 ----
    const census = forcingCensus(coins, true)

    log('census')

    const unionHeld = heldOf(unionHubStore(coins, 4, [0, 0, 0, 0]))
    const kinds = classKinds()
    const shifts: number[][] = []

    for (let x = 0; x < box.cells; x++) if (kinds[classOf(x, 4, [0, 0, 0, 0])] !== 'root') shifts.push([...(box.coords[x] as number[])])

    const lifts = census.minimal.map(G => ({ order: G.members.length, ...orientingLiftPairs(coins, box, unionHeld, G, shifts) }))

    log('lifts')

    const twoT = binaryTetrahedralIndices(table)
    const n4 = NORM4_KEYS()
    const patterns = [
      ...n4.map((c, i) => ({ name: `two lines (hub and norm-4 class ${i})`, start: [0, c] })),
      ...n4.map((c, i) => ({ name: `three lines (hub and the norm-4 classes but ${i})`, start: [0, ...n4.filter(d => d !== c)] })),
    ].map(p => {
      const held = coveringPattern(coins, box, twoT, p.start)
      const inside = insideSubgroups(coins, box, held, shifts, 600)
      let scalars = 0
      let shear = 0
      let largestScalar = 0

      for (const H of inside.subgroups) {
        if (H.members.length < 12) continue

        const f = huskForcing(coins, H.members)

        if (f.husk2 && f.husk4) {
          scalars++
          largestScalar = Math.max(largestScalar, H.members.length)
        }

        shear += f.husk2 && f.husk4 && f.huskShear2 ? 1 : 0
      }

      return { name: p.name, O: inside.O.length, subgroups: inside.subgroups.length, complete: inside.complete, scalars, largestScalar, shear }
    })

    log('patterns')

    const s1 =
      census.minimal.length === 1 &&
      census.forcingTwo.every(G => (census.minimal[0] as { members: number[] }).members.every(m => G.members.includes(m))) &&
      census.threeWithoutTwo === 0 &&
      lifts.every(l => l.orienting === 0) &&
      patterns.every(p => p.complete && p.shear === 0)

    // ---- T ----
    const o = orientedUnion(coins)
    const unionForcing = huskForcing(coins, o.group)
    const mesh = makeColorWeave({ side: 4, table: 'bind' }).mesh
    const docks = multiLineDockMatrices('lone', orientedUnionStore(coins, 4, [0, 0, 0, 0]), 256, coins)
    const medium = periodicMedium(mesh, docks.even, docks.odd)
    const ops = cellOps(medium)
    const { vectors: left, consistent } = leftInvariants(medium, namedDockInvariants())
    const residual = leftResidual(ops, left)
    const right = rightInvariants(ops, left)

    log('medium')

    const reading: SymmetricReading = readSymmetricTransport({ medium, left, right: right.vectors, directions: huskDirections(3), rungs: RUNGS, log: what => log(what) })
    const e = reading.exponent
    const t = residual < 1e-9 && consistent && (e.charge ?? 0) >= 3.5 && (e.trace ?? 0) >= 3.5 && (e.sound ?? 0) >= 3.5 && Math.abs((e.shear ?? 0) - 2) <= 0.5 && reading.sectorsClean
    const status = s0 && s1 ? (t ? 'pass' : 'fail') : 'partial'
    const fmt = (r: SymmetricReading): string => ['charge', 'trace', 'sound', 'shear', 'depth', 'slowTrace', 'mixedShear'].map(q => `${q} ${(r.exponent[q] ?? Number.NaN).toFixed(2)}`).join(', ')

    return verdict({
      status,
      claim: `no orientation of the coset-union store is kept by a group forcing the husk shear (the one minimal forcing group, of order ${census.minimal[0]?.members.length}, keeps an orientation with ${lifts.map(l => l.orienting).join(', ')} of ${lifts.map(l => l.tried).join(', ')} lift pairs), nor of the two- and three-line covering patterns; the oriented union (72 kept) reads on the husk ${fmt(reading)}`,
      metrics: {
        gateS0: s0 ? 1 : 0,
        gateS1: s1 ? 1 : 0,
        gateT: t ? 1 : 0,
        hubGroup: hub.group.length,
        carrierError,
        classes: census.classes,
        twoGenerated: census.twoGenerated,
        forcingTwo: census.forcingTwo.length,
        minimalOrder: census.minimal[0]?.members.length ?? 0,
        minimalCount: census.minimal.length,
        forcingConjugates: census.conjugates,
        threeClosures: census.threeClosures,
        threeDistinct: census.threeDistinct,
        threeForcing: census.threeForcing,
        threeWithoutTwo: census.threeWithoutTwo,
        liftPairsTried: lifts.reduce((s, l) => s + l.tried, 0),
        liftPairsOrienting: lifts.reduce((s, l) => s + l.orienting, 0),
        unionGroup: o.group.length,
        unionForcesScalars: unionForcing.husk2 && unionForcing.husk4 ? 1 : 0,
        unionForcesShear: unionForcing.huskShear2 ? 1 : 0,
        rowOrbits: docks.orbits,
        distinctRows: docks.distinct,
        leftResidual: residual,
        ...Object.fromEntries(Object.entries(e).map(([q, v]) => [`${q}_exponent`, v])),
        ...Object.fromEntries(Object.entries(reading.means).map(([q, v]) => [`${q}_mean`, v])),
        couplingPS: reading.couplingPS,
        seconds: (Date.now() - started) / 1000,
      },
      control: Object.fromEntries(patterns.flatMap((p, i) => [[`pattern${i}_O`, p.O], [`pattern${i}_subgroups`, p.subgroups], [`pattern${i}_scalarForcing`, p.scalars], [`pattern${i}_largestScalar`, p.largestScalar], [`pattern${i}_shearForcing`, p.shear]])),
      notes: `L2. Gates: S0 ${s0} (hub forcing ${JSON.stringify(hubForcing)}, hub orientation conflicts ${hubOriented.conflicts}, carrier error ${carrierError.toExponential(2)}), S1 ${s1}, T ${t}. Census: ${census.classes} classes, ${census.twoGenerated} two-generated subgroups, ${census.forcingTwo.length} force (orders ${census.forcingTwo.map(G => G.members.length).join(', ')}), minimal ${census.minimal.map(G => G.members.length).join(', ')}, ${census.conjugates} conjugates in all; three-generated ${census.threeClosures} closures, ${census.threeDistinct} distinct, ${census.threeForcing} forcing, ${census.threeWithoutTwo} without a forcing two-generated subgroup. Union lifts: ${lifts.map(l => `order ${l.order}: ${l.orienting} of ${l.tried}`).join('; ')}. Covering patterns: ${patterns.map(p => `${p.name}: O ${p.O}, ${p.subgroups} subgroups inside, ${p.scalars} force the scalars (largest ${p.largestScalar}), ${p.shear} the shear`).join('; ')}. Oriented union: ${o.group.length} kept, forcing ${JSON.stringify(unionForcing)}; ${docks.distinct} distinct rows in ${docks.orbits} orbits; left residual ${residual.toExponential(2)}, consistent ${consistent}; reading ${fmt(reading)}, anisotropy ${JSON.stringify(reading.anisotropy)}, means ${JSON.stringify(reading.means)}, coupling PS ${reading.couplingPS.toExponential(3)} SP ${reading.couplingSP.toExponential(3)}, sectors clean ${reading.sectorsClean}, iterations ${reading.iterations}. ${((Date.now() - started) / 1000).toFixed(0)} s.`,
    })
  },
})
