// The coset-union hub vacuum: every dock of the hub pattern's empty classes made a hub (E-RLT-0093).
//
// THE TARGET. The hub vacuum under L (E-RLT-0084 to 0092) is causally thin: 64 of its 512 husk columns are docks no
// vacuum pair streams through (E-RLT-0089), and a seed's dependence cone is its free star, 61 of 512 (E-RLT-0091).
// Wanted: (1a) one causal component with every husk dock descending from the seed, (1b) the seed's dependence cone
// covering every husk dock, while keeping (3) pair creation and (4) a bounded wake. (2) isotropy is E-RLT-0094 and
// (5) walls E-RLT-0095, on the same vacuum.
//
// THE COUNT, exact (code/measure/dense-hub). D4 / 2 D4 has 16 classes: the hub class 0, the 12 root classes, and 3
// classes of norm 4 (2 e1, (1,1,1,1), (1,1,1,-1)). A hub-vacuum unit at h + r streams its pair to h + r -+ r, both in
// class 0, so the vacuum's vibes visit {0} and the 12 root classes: 13 of 16. The 3 norm-4 classes are 768 of 4,096
// docks on the side-8 box and exactly the docks over the 64 husk columns whose three husk coordinates are all odd.
// THREE CANDIDATES, reasoned before any run:
//  (i) A SCHEDULE of the same store cannot reach them. From class 0 every root step lands in a root class; from a root
//      class rho a step along r lands in class 0 only for r = +-r(rho), and in a norm-4 class only along another line
//      of rho's triality frame. A vacuum vibe leaves its unit along the unit's own line and is turned at a hub, which
//      sends it along a root from class 0, to a root class. No order of the pieces changes where a vibe can be.
//  (ii) A COLLISION that scatters inside the empty classes cannot. An empty dock holds only what arrives; one arriving
//      vibe is the whole dock, and a collision keeping count and momentum must return one vibe of momentum r: the vibe
//      on slot r. So an empty dock is transparent to a lone difference by the conservation laws alone. It scatters only
//      what two differences bring together, which one seed's change never does at its first passage.
//  (iii) A DENSER PATTERN can. D4 / L' = Z2 x Z2, with L' = {0} + the three norm-4 classes (index 4) and the other three
//      cosets the three triality frames. W(F4) about a hub fixes class 0 and permutes the norm-4 classes transitively
//      (its triality quotient), so a W(F4)-invariant pattern fills all three or none, and each norm-4 class is the hub
//      class of the hub pattern translated by it. The union of the four translates by L' / 2 D4 stores on a dock of
//      root class rho the lines of rho - c, c in L' / 2 D4: four distinct lines, exactly rho's frame. So no unit is
//      stored twice, every dock of L' is a hub receiving 24 vibes, and (Z) holds term by term. It covers every dock by
//      construction. The four parts share no slot at any beat, so the union RUNS as four independent hub vacua.
// THE ORIENTATION (found after a probe, disclosed): the four translated orientations keep only 24 elements (no forcing);
// oriented instead under 2T and one more element (code/measure/dense-hub orientedUnion, the least extra element, 37),
// the union keeps 72 elements and forces the husk scalars but not the shear (E-RLT-0094 proves no orientation does).
// This oriented union is the candidate.
//
// (1b) IS FORCED TO FAIL UNDER L, a theorem stated before the run. LINE LOCALITY: under L a dock holding at most one
// single line turns its full lines as -1 and moves nothing else, so a dock state that is the vacuum's with the content
// of ONE line changed collides to the vacuum's image with only that line changed (the other lines are full or empty,
// and -1 on a full line is what the vacuum does to it). The pair move reads and writes one line and its own store.
// The stream copies a slot along its own line. So a change confined to one line through a dock stays on that line
// forever, and every change of one slot or one store of the seed dock is confined to one line. The seed's cone is
// therefore inside the union of the 12 lines through it: the free star (61 of 512 husk docks on side 8), whatever the
// vacuum, at every beat count. A vacuum that fills every dock cannot help: covering needs a collision that moves a
// one-line difference onto another line, which is exactly what E-RLT-0084's wake gate B6 forbids for a lone vibe (0
// trits off its line). K does it (and covers), and its wake is the thing L was built to stop.
//
// Gates, fixed before this file's first run (probes tmp/dense-probe1.ts to dense-probe7.ts measured most of these
// numbers at integer+0 first, disclosed; the wake and the cone were probed on the translate union, not this oriented
// one):
//  U0 the instrument (integer+0): the union stores no unit twice and stores exactly the four frame lines on every root
//     dock and nothing on the 1,024 docks of L'; (Z) holds at every dock; the union's vacuum equals its four parts
