// Canon part two under the adopted rule, first results, and both are physics the committed
// rule did not have:
//
//   - THE RELIC BACKGROUND. Under the static weave, a commensurate growth quench left ZERO
//     wall content, an exact null. Under the adopted turning weave NO quench rate is null:
//     domain formation permanently scatters radiation into the bulk, a relic background of
//     the universe's own growth history, exactly the structure cosmology observes. The relic
//     is lawful: its content is a WHOLE NUMBER OF HYPERSHEETS at every settled beat of every
//     quench rate, and the deep-commensurate rates carry the least of it (the k twenty-four
//     quench floor sits at forty-eight sheets against one hundred seventy-four at k one),
//     though the ordering is not monotone across all rates, reported as measured.
//   - MASS FROM DRESSING. The protected species is EXACTLY ballistic (single cell, exactly
//     one D4 step per beat for eight beats, speed root two, massless). The interacting
//     species move at a fraction of that (their difference-field centroids displace about
//     one to three cells in eight beats), and DIFFERENT species move at DIFFERENT fractions.
//     Interaction with the vacuum generates effective mass, and the mass differs by species
//     under one rule, the phenomenological shape the mass-hierarchy rows need.
//
// Depth L2, deterministic, the protected species the massless control for the mass half and
// the sheet quantization itself the lawfulness control for the relic half.

import { experiment } from '@/test/scaffold/suite'
import { verdict } from '@/test/scaffold/verdict'
import { d4Mesh, meshOpposites } from '@/code/tool/mesh'
import { makeWill, Will } from '@/code/tone/will'
import { beat, growingBeat } from '@/code/rule/lattice-gas'
import { turningWeave } from '@/code/rule/collision'

const SIDE = 13

export default experiment({
  id: 'foundations/turning-weave-relic-and-mass',
  code: 'E-FND-0120',
  title:
    'the adopted rule has a relic background and mass from dressing: no growth quench rate is null (domain formation permanently scatters radiation into the bulk, the model growing its own relic background where the static weave had an exact commensurate null), the relic content is a whole number of hypersheets at every settled beat of every rate with the deep-commensurate rates carrying the least, and the protected species is exactly ballistic at speed root two while the interacting species move at species-dependent fractions of it, effective mass generated by interaction with the vacuum and differing by species under one rule',
  category: 'foundations',
  substrates: ['3434'],
  depth: 'L2',
  paper: true,
  run() {
    const mesh = d4Mesh({ side: SIDE })
    const opposite = meshOpposites(mesh)
    const rule = turningWeave({ opposite })
    const coordinate = (c: number, a: number): number =>
      Math.floor(c / SIDE ** a) % SIDE
    const sheet = SIDE * SIDE * SIDE

    // the relic sweep
    const relicFloor = (k: number): {
      quantized: boolean
      floorSheets: number
      everNull: boolean
    } => {
      let staggered: Will = makeWill(mesh)
      let uniform: Will = makeWill(mesh)
      let quantized = true
      let least = Infinity
      let everNull = false

      for (let t = 0; t < 96; t++) {
        const bornThrough = Math.min(SIDE - 1, Math.floor((t + 1) / k))
        const active = (c: number): boolean =>
          coordinate(c, 0) <= bornThrough

        staggered = growingBeat(staggered, rule(t), active)
        uniform = growingBeat(uniform, rule(t), () => true)

        if (t >= 72) {
          let wall = 0

          for (let i = 0; i < staggered.data.length; i++) {
            if (staggered.data[i] !== uniform.data[i]) {
              wall++
            }
          }

          if (wall % sheet !== 0) {
            quantized = false
          }

          if (wall === 0) {
            everNull = true
          }

          least = Math.min(least, wall)
        }
      }

      return { quantized, floorSheets: least / sheet, everNull }
    }

    const k1 = relicFloor(1)
    const k12 = relicFloor(12)
    const k24 = relicFloor(24)

    // the mass split at side seventeen, eight clean beats
    const side17 = 17
    const mesh17 = d4Mesh({ side: side17 })
    const rule17 = turningWeave({ opposite: meshOpposites(mesh17) })
    const mid = 8
    const center17 =
      mid + mid * side17 + mid * side17 * side17 + mid * side17 ** 3
    const wrap17 = (d: number): number =>
      d > side17 / 2 ? d - side17 : d < -side17 / 2 ? d + side17 : d
    const coordinate17 = (c: number, a: number): number =>
      Math.floor(c / side17 ** a) % side17

    const speedOf = (
      dir: number,
    ): { displacement: number; exactBallistic: boolean } => {
      let vacuum: Will = makeWill(mesh17)
      let seeded: Will = makeWill(mesh17)

      seeded.data[center17 * 24 + dir] = 1

      const to = mesh17.neighbour(center17, dir)
      const step = [0, 1, 2, 3].map(a =>
        wrap17(coordinate17(to, a) - mid),
      )
      let displacement = 0
      let exactBallistic = true

      for (let t = 0; t < 8; t++) {
        vacuum = beat(vacuum, rule17(t))
        seeded = beat(seeded, rule17(t))

        const cells = new Set<number>()

        for (let i = 0; i < seeded.data.length; i++) {
          if (seeded.data[i] !== vacuum.data[i]) {
            cells.add(Math.floor(i / 24))
          }
        }

        const sum = [0, 0, 0, 0]

        for (const c of cells) {
          for (let a = 0; a < 4; a++) {
            sum[a]! += wrap17(coordinate17(c, a) - mid)
          }
        }

        const n = cells.size || 1
        const centroid = sum.map(v => v / n)

        if (t === 7) {
          displacement = Math.hypot(...centroid)
        }

        const expected = step.map(v => v * (t + 1))

        if (
          !(
            cells.size === 1 &&
            centroid.every(
              (v, a) => Math.abs(v - expected[a]!) < 1e-9,
            )
          )
        ) {
          exactBallistic = false
        }
      }

      return { displacement, exactBallistic }
    }

    const massless = speedOf(0)
    const heavy = speedOf(8)
    const middleweight = speedOf(4)
    const ballistic = 8 * Math.SQRT2

    const ok =
      k1.quantized &&
      k12.quantized &&
      k24.quantized &&
      !k1.everNull &&
      !k12.everNull &&
      !k24.everNull &&
      k24.floorSheets < k12.floorSheets &&
      k12.floorSheets < k1.floorSheets &&
      massless.exactBallistic &&
      Math.abs(massless.displacement - ballistic) < 1e-9 &&
      heavy.displacement < ballistic / 2 &&
      middleweight.displacement < ballistic / 2 &&
      middleweight.displacement > heavy.displacement + 0.5

    return verdict({
      status: ok ? 'pass' : 'fail',
      claim:
        'every settled beat of every measured quench is sheet-quantized with no null anywhere, the relic floor falls with commensurability across k one, twelve, twenty-four, the protected species is exactly ballistic to the last decimal, and the two interacting species move at distinct fractions below half of light speed',
      metrics: {
        relicFloorK1: k1.floorSheets,
        relicFloorK12: k12.floorSheets,
        relicFloorK24: k24.floorSheets,
        masslessDisplacement: Number(
          massless.displacement.toFixed(2),
        ),
        heavyDisplacement: Number(heavy.displacement.toFixed(2)),
        middleweightDisplacement: Number(
          middleweight.displacement.toFixed(2),
        ),
        ballisticReference: Number(ballistic.toFixed(2)),
      },
      // CONTROL: the protected species, same instrument, exactly massless
      control: {
        masslessExactlyBallistic: massless.exactBallistic ? 1 : 0,
      },
      notes:
        'the relic ordering is not monotone across ALL rates (k three carries more than k one), reported as measured, and the gate holds only the deep-commensurate ordering. The mass half is a centroid measure on a radiating cloud, an effective-speed statement rather than a dispersion relation: the dispersion relation proper is the coarse-bridge deliverable. What this supplies the mass rows is the mechanism shape: one rule, massless protected species, and interaction-generated masses that differ by species.',
    })
  },
})
