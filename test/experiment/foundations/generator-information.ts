// Base-generator family B, the INFORMATION seeds, the geometry from the tone. The committed 24-cell dock is the
// deterministic output of two information seeds: four ternary tones (B1, the norm-2 shell of {-1,0,+1}^4), and a
// binary code (B2, the even-weight code via Construction A gives the D4 lattice whose minimal vectors are the
// dock). Plan: theory-v0.8.0/plans/the-base-generator.md. Companion math: code/algebra/group/root-system.ts.

import { experiment } from '@/test/scaffold/suite'
import { verdict } from '@/test/scaffold/verdict'
import {
  ternaryShells,
  rootsD4,
  vectorKey,
  evenWeightCode,
  constructionAMinimalVectors,
} from '@/code/algebra/group/root-system'
import { automorphismGroupOrder } from '@/code/algebra/group/automorphism'

function sameSet(left: number[][], right: number[][]): boolean {
  const a = new Set(left.map(vectorKey))
  const b = new Set(right.map(vectorKey))

  return a.size === b.size && [...a].every(key => b.has(key))
}

// B1, the tone seed: the dock is the norm-2 shell of four ternary tones.
export default experiment({
  id: 'foundations/generator-tone-shell',
  title:
    'the 24-cell dock is the norm-2 shell of {-1,0,+1}^4, the geometry is the tone',
  category: 'foundations',
  substrates: ['3434'],
  depth: 'L1',
  paper: true,
  run() {
    const shells = ternaryShells(4)
    const shellSizes = {
      one: shells.get(1)?.length ?? 0, // 16-cell
      two: shells.get(2)?.length ?? 0, // 24-cell (the dock)
      three: shells.get(3)?.length ?? 0, // 32-cell
      four: shells.get(4)?.length ?? 0, // tesseract
    }

    const normTwoShell = shells.get(2) ?? []
    const isDock = sameSet(normTwoShell, rootsD4())
    const fullSymmetry = automorphismGroupOrder(rootsD4()) // F4, order 1152
    const ok =
      shellSizes.one === 8 &&
      shellSizes.two === 24 &&
      shellSizes.three === 32 &&
      shellSizes.four === 16 &&
      isDock &&
      fullSymmetry === 1152

    return verdict({
      status: ok ? 'pass' : 'fail',
      claim:
        'the squared-length-two shell of the four ternary tones {-1,0,+1}^4 is exactly the 24 D4 directions of the dock, with full symmetry F4 of order 1152, so the geometry is generated by the tone',
      metrics: {
        shell16cell: shellSizes.one,
        shell24cell: shellSizes.two,
        shell32cell: shellSizes.three,
        shellTesseract: shellSizes.four,
        f4Order: fullSymmetry,
      },
    })
  },
})

// B2, the binary-code seed: the even-weight code gives D4 by Construction A, whose minimal vectors are the dock.
experiment({
  id: 'foundations/generator-binary-code',
  title:
    'the even-weight binary code gives the D4 lattice (Construction A) whose minimal vectors are the dock',
  category: 'foundations',
  substrates: ['3434'],
  depth: 'L1',
  paper: true,
  run() {
    const code = evenWeightCode(4) // the [4,3,2] even-weight code
    const minimal = constructionAMinimalVectors(code, 4)
    const isDock = sameSet(minimal, rootsD4())
    const ok = code.length === 8 && minimal.length === 24 && isDock

    return verdict({
      status: ok ? 'pass' : 'fail',
      claim:
        'the even-weight binary code in four bits, lifted by Construction A, yields the D4 lattice whose 24 minimal vectors are exactly the dock, so the geometry also comes from a binary code',
      metrics: {
        codewords: code.length,
        minimalVectors: minimal.length,
      },
    })
  },
})
