// Links as vibe-vibe relations, the algebra (code/rule/relational-links). The user's formulation: a dock has
// 24 slots, one per direction, each holding one vibe, and the edge between docks x and y is shared by x's
// slot toward y and y's slot toward x. The link would be the relation between those two vibes, not a third
// object. Recent gauge work (E-FRC-0117, 0128, 0144, 0150 to 0165) stored independent state per edge. This
// asks what a relation of the two slots can carry, and at what price.
//
// The known obstacle: a link that is a function of its two endpoint DOCKS' current states, h_y h_x^-1, is pure
// gauge and every loop is trivial. A slot is not a dock. A dock has 24 slots, and the two slots of an edge
// are different slots at each end, so the relation of slots escapes that obstacle. Two other things decide it.
//
// A. What a relation can be (exhaustive, L1). A relation f(p, q) is a link only if it moves as one under a
//    change of frame in every dock: f(g_x p, g_y q) = g_y f(p, q) g_x^-1. For a slot content p and a gauged
//    group H, the census counts the H x H orbits on pairs and the link values each admits, by brute force
//    over the stabilizers, and the link values the covariant relations reach:
//    A1 role and tilt (a point of the 3 x 3 grid) under the 216 grid moves, the 24 turns SL(2, 3) and the 9
//       translations. Role and tilt with the vibe (27 contents, the vibe unmoved by a frame). The torsors:
//       role and tilt with a turn acted on by the frame (the 216 moves themselves), and a full Sigma(648)
//       frame
//    A2 the global turns: with local translations gauged and one turn for all docks, the values a relation
//       can take are T_q c T_-p with c commuting with all 24 turns. Counted
//    A3 every subgroup of the 216 generated by two elements, and which act freely on the 9 points: the
//       gauged groups a role point's relation can carry
//    A4 the turn between the two slots of an edge, read from the coin group of E-FRC-0104: the element t
//       with t o d = -d, for each of the 24 directions
//    A5 the center: the relation of two role points is a translation, and the elements of Sigma(648) over
//       the translations are the Heisenberg group of 27. With the center phase from a history such as the
//       flux (which no frame moves), covariance under local translations needs a section s with
//       s(u + t_y - t_x) = s(t_y) s(u) s(t_x)^-1. The mismatches over the 729 triples, fewest over all 3^8
//       sections, and with a local center phase. Control: each slot holding its own Heisenberg element
// B. What a relation does (L1 fills, L2 dynamics), on the D4 box:
//    B1 curvature: every slot a hashed point, or a hashed frame of the 216 or of Sigma(648), each link the
//       relation of its two slots, the holonomy of every triangle. Controls: one point or frame per dock,
//       every slot of a dock alike, which is the pure-gauge case. Also the role points of the color weave
//       after 24 beats from a dense start
//    B2 the knit: in the slot knit every slot streams every beat, so the two slots of an edge are exactly the
//       two contents crossing it. The color weave with each crossing role point carried by the relation of
//       the two crossing points (code/rule/relationalColorBeat), against the color weave's stored links. On
//       the side-5 box from the dense start of E-FRC-0128, for each of the 24 slots of dock 0, its role point
//       set to each of the 9 values, 6 beats: the docks where the 9 runs differ, and how far they are from
//       dock 0. Frame covariance of both, a change of frame by all 216 in every dock, 24 beats, with the
//       E-FRC-0117 control (roles moved, links not)
//
// Gates, fixed before the run:
// - A1: no covariant relation of role points under the 216 or the 24, one under the 9 translations; the vibe
//   adds none; both torsors admit one, reaching every value
// - A3: every subgroup acting freely on the 9 points has order at most 9, and the translations are one
// - A4: one relative turn for all 24 directions, central and of order 2
// - A5: the fewest mismatches over all sections above 0; the torsor control 0
// - B1: the point fill's triangles are trivial within 0.01 of 1/9 of the time, the Sigma(648) fill's mean
//   Re Tr / 3 within 0.02 of 0, and both dock controls trivial on every triangle
//
// The run, recorded as it came out. The point fill failed its gate: its triangles are trivial 0.324 of the
// time, not 1/9. The fill is the golden-ratio hash of the slot index, a Weyl sequence, and a triangle's
// holonomy is a signed sum of slot points at fixed index offsets within each dock, which a Weyl sequence
// makes nearly constant. That is the relation doing its job (it reads the differences between a dock's
// slots, and this fill's differences are structured), not a property of the relation. The frame fills
// scramble through the group product and read the Haar values. The gate was moved, after that run and
// disclosed here, to the knit's own role points: the color weave run 24 beats from the dense start of
// E-FRC-0128, whose triangles are trivial 0.110 of the time against 1/9. The Weyl fill is still reported.
// - B2: under the relation no perturbation leaves dock 0 in 6 beats, for any of the 24 slots, while the
//   stored links carry at least one out; the relational rule commutes with the 216 frame change (0
//   mismatches), the stored rule too with its links changed, and the E-FRC-0117 control does not
//
// Depth L1: known group theory (a covariant relation needs a torsor, the split link of lattice gauge
// theory), computed exhaustively, with the knit run for B2.

import { experiment } from '@/test/scaffold/suite'
import { verdict } from '@/test/scaffold/verdict'
import { colorBeat, makeColorWeave, type ColorWeave } from '@/code/rule/color-weave'
import {
  actsFreely,
  centerCocycle,
  directionRelation,
  gridTable,
  relationalColorBeat,
  relationCensus,
  subgroupsFromPairs,
  times,
  triangleHolonomies,
  type GroupTable,
  type SlotAction,
  type TriangleMesh,
} from '@/code/rule/relational-links'
import { makeSigmaLinks } from '@/code/rule/sigma-links'
import { d4BoxDistance } from '@/code/substrate/d4-box'
import { gridMoves, type VibeState } from '@/code/rule/vibe-weave'

const GOLDEN = (Math.sqrt(5) - 1) / 2
const FILL_SIDE = 4
const KNIT_SIDE = 5
const KNIT_BEATS = 6
const FRAME_BEATS = 24

const hash = (i: number, scale: number, range: number): number => Math.floor((((i + 1) * GOLDEN * scale) % 1) * range)

export default experiment({
  id: 'gauge/relational-links',
  code: 'E-FRC-0174',
  title:
    "links as vibe-vibe relations, the algebra: a relation of the two slots of an edge is a covariant link only if each slot holds a frame on which the gauged group acts freely, so role and tilt carry the 9 translations of the 216 and no more, the turn between an edge's two slots is the same central -1 for all 24 directions, and the center cannot ride the role points' relation with a flux history under any of the 6,561 sections; the relation of slots is not pure gauge (on the knit's own role points a triangle is trivial 0.110 of the time against 1/9, with one point per dock always), but in the knit, where both slots of an edge are the two contents crossing it, the relation carries each role point onto its partner's and no role point ever leaves its dock",
  category: 'gauge',
  substrates: ['3434'],
  depth: 'L1',
  paper: false,
  run() {
    const moves = gridMoves()
    const grid = gridTable(moves)
    const all = Array.from({ length: grid.order }, (_, g) => g)
    const turns = all.filter(g => moves.act[g]?.[0] === 0)
    const shifts = all.filter(g => Array.from({ length: 9 }, (_, p) => p).every(p => {
      const s = moves.act[g]?.[0] ?? 0

      return moves.act[g]?.[p] === ((p % 3) + (s % 3)) % 3 + 3 * ((Math.floor(p / 3) + Math.floor(s / 3)) % 3)
    }))
    const shiftTo = (p: number): number => shifts.find(g => moves.act[g]?.[0] === p) ?? grid.identity

    // A1: the census
    const points: SlotAction = { table: grid, points: 9, act: (g, p) => moves.act[g]?.[p] ?? 0 }
    const pointsWithVibe: SlotAction = { table: grid, points: 27, act: (g, p) => (moves.act[g]?.[p % 9] ?? 0) + 9 * Math.floor(p / 9) }
    const torsor216: SlotAction = { table: grid, points: grid.order, act: (g, f) => times(grid, g, f) }
    const sigma = makeSigmaLinks({ side: 3, kappa: 0, tension: 0, capacity: 1 })
    const sigmaTable: GroupTable = { order: sigma.order, product: sigma.group.product, inverse: sigma.group.inverse, identity: sigma.identity }
    const torsor648: SlotAction = { table: sigmaTable, points: sigma.order, act: (g, f) => times(sigmaTable, g, f) }
    const census = {
      pointsFull: relationCensus({ action: points, gauged: all }),
      pointsTurns: relationCensus({ action: points, gauged: turns }),
      pointsShifts: relationCensus({ action: points, gauged: shifts }),
      pointsVibeFull: relationCensus({ action: pointsWithVibe, gauged: all }),
      pointsVibeShifts: relationCensus({ action: pointsWithVibe, gauged: shifts }),
      torsor216: relationCensus({ action: torsor216, gauged: all }),
      torsor648: relationCensus({ action: torsor648, gauged: Array.from({ length: sigma.order }, (_, g) => g) }),
    }

    // A2: local translations with one global turn: c must commute with all 24 turns
    const centralizer = all.filter(c => turns.every(l => times(grid, c, l) === times(grid, l, c)))
    const reachable = new Set<number>()

    for (let p = 0; p < 9; p++) {
      for (let q = 0; q < 9; q++) {
        for (const c of centralizer) {
          reachable.add(times(grid, shiftTo(q), times(grid, c, grid.inverse[shiftTo(p)] ?? 0)))
        }
      }
    }

    // A3: free subgroups
    const subgroups = subgroupsFromPairs(grid)
    const free = subgroups.filter(h => actsFreely(points, h))
    const freeOrders = free.map(h => h.length)
    const shiftKey = [...shifts].sort((a, b) => a - b).join(',')
    const translationsFree = free.some(h => h.join(',') === shiftKey)

    // A4, A5
    const direction = directionRelation()
    const cocycle = centerCocycle(sigma)

    // B1: curvature from fills on the side-4 box
    const box = makeSigmaLinks({ side: FILL_SIDE, kappa: 0, tension: 0, capacity: 1 })
    const mesh: TriangleMesh = { cells: box.cells, neighbour: box.neighbour, opposite: box.opposite, staples: box.staples }
    const slots = box.cells * 24
    const pointFill = Int16Array.from({ length: slots }, (_, i) => shiftTo(hash(i, 3.3, 9)))
    const pointDock = Int16Array.from({ length: slots }, (_, i) => shiftTo(hash(Math.floor(i / 24), 3.3, 9)))
    const frameFill = Int16Array.from({ length: slots }, (_, i) => hash(i, 4.1, grid.order))
    const sigmaFill = Int16Array.from({ length: slots }, (_, i) => hash(i, 5.7, sigma.order))
    const sigmaDock = Int16Array.from({ length: slots }, (_, i) => hash(Math.floor(i / 24), 5.7, sigma.order))
    const trivialShare = (h: Float64Array, table: GroupTable): number => (h[table.identity] ?? 0) / h.reduce((a, b) => a + b, 0)
    const meanTrace = (h: Float64Array): number => h.reduce((a, n, g) => a + n * ((sigma.group.trace[g] ?? 0) / 3), 0) / h.reduce((a, b) => a + b, 0)
    // total variation from uniform over the given support
    const variation = (h: Float64Array, support: readonly number[]): number => {
      const total = h.reduce((a, b) => a + b, 0)
      const inside = new Set(support)

      return (
        0.5 *
        h.reduce((a, n, g) => a + Math.abs(n / total - (inside.has(g) ? 1 / support.length : 0)), 0)
      )
    }

    const pointHolonomy = triangleHolonomies({ mesh, frames: pointFill, table: grid })
    const pointDockHolonomy = triangleHolonomies({ mesh, frames: pointDock, table: grid })
    const frameHolonomy = triangleHolonomies({ mesh, frames: frameFill, table: grid })
    const sigmaHolonomy = triangleHolonomies({ mesh, frames: sigmaFill, table: sigmaTable })
    const sigmaDockHolonomy = triangleHolonomies({ mesh, frames: sigmaDock, table: sigmaTable })
    const nonShift = pointHolonomy.reduce((a, n, g) => a + (shifts.includes(g) ? 0 : n), 0)

    // the role points of the color weave after 24 beats from a dense start, as a fill
    const fillWeave = makeColorWeave({ side: FILL_SIDE })
    const dense = (weave: ColorWeave, scale: number): VibeState => {
      const n = weave.mesh.cellCount * 24
      const vibe = new Int8Array(n)
      const role = new Int8Array(n)

      for (let i = 0; i < n; i++) {
        const u = ((i + 1) * GOLDEN * scale) % 1

        vibe[i] = u < 0.3 ? -1 : u < 0.6 ? 0 : 1
        role[i] = Math.floor(((i + 3) * GOLDEN * scale * 9) % 9)
      }

      return { vibe, role, flow: new Int32Array(n) }
    }

    let evolved = dense(fillWeave, 1.37)

    for (let t = 0; t < 24; t++) {
      evolved = colorBeat(fillWeave, evolved, t)
    }

    const weaveHolonomy = triangleHolonomies({ mesh, frames: Int16Array.from(evolved.role, p => shiftTo(p)), table: grid })

    // B2: the knit
    const weave = makeColorWeave({ side: KNIT_SIDE })
    const start = dense(weave, 1.37)
    const run = (beat: (s: VibeState, t: number) => VibeState, s0: VibeState, beats: number): VibeState => {
      let s = s0

      for (let t = 0; t < beats; t++) {
        s = beat(s, t)
      }

      return s
    }
    const stored = (s: VibeState, t: number): VibeState => colorBeat(weave, s, t)
    const relational = (s: VibeState, t: number): VibeState => relationalColorBeat(weave, s, t)
    const spread = (beat: (s: VibeState, t: number) => VibeState): { left: number; docks: number; farthest: number } => {
      let left = 0
      let docks = 0
      let farthest = 0

      for (let d = 0; d < 24; d++) {
        const finals = Array.from({ length: 9 }, (_, p) => {
          const role = Int8Array.from(start.role)

          role[d] = p

          return run(beat, { vibe: start.vibe, role, flow: start.flow }, KNIT_BEATS)
        })
        const differ = new Set<number>()

        for (const f of finals.slice(1)) {
          f.role.forEach((p, i) => {
            if (p !== finals[0]?.role[i]) {
              differ.add(Math.floor(i / 24))
            }
          })
        }

        const reach = Math.max(0, ...[...differ].map(x => d4BoxDistance({ a: 0, b: x, side: KNIT_SIDE })))

        left += reach > 0 ? 1 : 0
        docks += differ.size / 24
        farthest = Math.max(farthest, reach)
      }

      return { left, docks, farthest }
    }
    const storedSpread = spread(stored)
    const relationalSpread = spread(relational)

    // frame covariance, a frame of the 216 in every dock
    const { mesh: knitMesh } = weave
    const frame = Array.from({ length: knitMesh.cellCount }, (_, x) => hash(x + 10, 5.9, grid.order))
    const turnRoles = (s: VibeState): VibeState => ({
      ...s,
      role: Int8Array.from(s.role, (p, i) => moves.act[frame[Math.floor(i / 24)] ?? 0]?.[p] ?? 0),
    })
    const turnLinks = (links: Int16Array): Int16Array =>
      Int16Array.from(links, (u, i) => {
        const x = Math.floor(i / 24)
        const y = knitMesh.neighbour(x, i % 24)

        return times(grid, times(grid, frame[y] ?? 0, u), grid.inverse[frame[x] ?? 0] ?? 0)
      })
    const mismatches = (beatA: (s: VibeState, t: number) => VibeState, beatB: (s: VibeState, t: number) => VibeState): number => {
      let a = dense(weave, 2.11)
      let b = turnRoles(a)
      let n = 0

      for (let t = 0; t < FRAME_BEATS; t++) {
        a = beatA(a, t)
        b = beatB(b, t)

        const expected = turnRoles(a)

        n += expected.role.filter((p, i) => p !== b.role[i]).length
      }

      return n
    }
    const turned = { ...weave, links: turnLinks(weave.links) }
    const relationalFrame = mismatches(relational, relational)
    const storedFrame = mismatches(stored, (s, t) => colorBeat(turned, s, t))
    const withoutLinks = mismatches(stored, stored)

    // a torsor riding the vibe: the transported frame U F_p with U = F_q F_p^-1 is F_q, for every pair
    let partner = 0

    for (let p = 0; p < grid.order; p++) {
      for (let q = 0; q < grid.order; q++) {
        const u = times(grid, q, grid.inverse[p] ?? 0)

        partner += times(grid, u, p) === q ? 1 : 0
      }
    }

    const a1 =
      !census.pointsFull.covariant &&
      !census.pointsTurns.covariant &&
      census.pointsShifts.covariant &&
      !census.pointsVibeFull.covariant &&
      census.torsor216.covariant &&
      census.torsor216.values === grid.order &&
      census.torsor648.covariant &&
      census.torsor648.values === sigma.order
    const a3 = Math.max(...freeOrders) <= 9 && translationsFree
    const a4 = direction.leftDistinct === 1 && direction.rightDistinct === 1 && direction.central && direction.involution
    const a5 = cocycle.fewestMismatches > 0 && cocycle.torsorMismatches === 0
    const b1 =
      Math.abs(trivialShare(weaveHolonomy, grid) - 1 / 9) < 0.01 &&
      Math.abs(meanTrace(sigmaHolonomy)) < 0.02 &&
      trivialShare(pointDockHolonomy, grid) === 1 &&
      trivialShare(sigmaDockHolonomy, sigmaTable) === 1
    const b2 =
      relationalSpread.left === 0 &&
      storedSpread.left > 0 &&
      relationalFrame === 0 &&
      storedFrame === 0 &&
      withoutLinks > 0

    const row = (name: string, c: typeof census.pointsFull): [string, number][] => [
      [`${name}SlotOrbits`, c.slotOrbits],
      [`${name}PairOrbits`, c.pairOrbits],
      [`${name}PairOrbitsWithValue`, c.pairOrbitsWithValue],
      [`${name}LargestStabilizer`, c.largestStabilizer],
      [`${name}Covariant`, c.covariant ? 1 : 0],
      [`${name}ValuesReached`, c.values],
    ]

    return verdict({
      status: a1 && a3 && a4 && a5 && b1 && b2 ? 'pass' : 'fail',
      claim:
        "a covariant relation of two slots exists only when the gauged group acts freely on what a slot holds: role and tilt admit none under the 216 grid moves or the 24 turns and one under the 9 translations, the vibe adds none, and a slot holding a whole frame of the 216 or of Sigma(648) admits one reaching every value; every subgroup acting freely on the 9 points has order at most 9; the turn between an edge's two slots is one central involution for all 24 directions; no section lets the center ride the role points' relation with a flux history; the relation of slots is not pure gauge, while one point or frame per dock is; and in the knit the relation of the two crossing role points keeps every role point in its dock, while stored links carry it away",
      metrics: Object.fromEntries([
        ...row('rolePointsUnderAll216', census.pointsFull),
        ...row('rolePointsUnderTurns24', census.pointsTurns),
        ...row('rolePointsUnderTranslations9', census.pointsShifts),
        ...row('rolePointsWithVibeUnderAll216', census.pointsVibeFull),
        ...row('rolePointsWithVibeUnderTranslations9', census.pointsVibeShifts),
        ...row('torsor216', census.torsor216),
        ...row('torsor648', census.torsor648),
        ['globalTurnCentralizer', centralizer.length],
        ['valuesWithLocalTranslationsAndGlobalTurns', reachable.size],
        ['subgroupsFromPairs', subgroups.length],
        ['freeSubgroups', free.length],
        ['freeSubgroupsOrder9', freeOrders.filter(n => n === 9).length],
        ['freeSubgroupsOrder3', freeOrders.filter(n => n === 3).length],
        ['largestFreeSubgroup', Math.max(...freeOrders)],
        ['translationsAmongFree', translationsFree ? 1 : 0],
        ['edgeTurnDistinctLeft', direction.leftDistinct],
        ['edgeTurnDistinctRight', direction.rightDistinct],
        ['edgeTurnCentral', direction.central ? 1 : 0],
        ['edgeTurnInvolution', direction.involution ? 1 : 0],
        ['centerSections', cocycle.sections],
        ['centerTriples', cocycle.triples],
        ['centerFewestMismatches', cocycle.fewestMismatches],
        ['centerMostMismatches', cocycle.mostMismatches],
        ['centerTriplesWithLocalCenter', cocycle.triplesWithCenter],
        ['centerFewestMismatchesWithLocalCenter', cocycle.fewestMismatchesWithCenter],
        ['centerTorsorMismatches', cocycle.torsorMismatches],
        ['pointFillTrivialShare', trivialShare(pointHolonomy, grid)],
        ['pointFillVariationFromUniform9', variation(pointHolonomy, shifts)],
        ['pointFillNonTranslationHolonomies', nonShift],
        ['frame216FillTrivialShare', trivialShare(frameHolonomy, grid)],
        ['frame216FillVariationFromUniform', variation(frameHolonomy, all)],
        ['sigmaFillTrivialShare', trivialShare(sigmaHolonomy, sigmaTable)],
        ['sigmaFillMeanReTrace', meanTrace(sigmaHolonomy)],
        ['sigmaFillVariationFromUniform', variation(sigmaHolonomy, Array.from({ length: sigma.order }, (_, g) => g))],
        ['colorWeaveRolesTrivialShare', trivialShare(weaveHolonomy, grid)],
        ['colorWeaveRolesVariationFromUniform9', variation(weaveHolonomy, shifts)],
        ['triangleStarts', pointHolonomy.reduce((a, b) => a + b, 0)],
        ['relationalSlotsWhosePointLeavesDock', relationalSpread.left],
        ['relationalMeanDocksDiffering', relationalSpread.docks],
        ['relationalFarthest', relationalSpread.farthest],
        ['storedSlotsWhosePointLeavesDock', storedSpread.left],
        ['storedMeanDocksDiffering', storedSpread.docks],
        ['storedFarthest', storedSpread.farthest],
        ['relationalFrameMismatches', relationalFrame],
        ['storedFrameMismatches', storedFrame],
        ['riderTransportedOntoPartner', partner],
        ['riderPairs', grid.order ** 2],
      ]),
      control: {
        pointDockTrivialShare: trivialShare(pointDockHolonomy, grid),
        sigmaDockTrivialShare: trivialShare(sigmaDockHolonomy, sigmaTable),
        sigmaDockMeanReTrace: meanTrace(sigmaDockHolonomy),
        rolesWithoutLinksFrameMismatches: withoutLinks,
      },
      notes:
        "L1, exact, no random numbers. The census is the orbit-stabilizer fact that a covariant function of (p, q) into the gauge group must satisfy h U g^-1 = U on each pair's stabilizer, so it exists only if both stabilizers are trivial: the slot must hold a torsor of the gauged group, a frame. Role and tilt are 9 points with stabilizer 24 under the 216, so only a group of order 9 acting freely can be gauged by them, and the vibe, which no frame moves, adds nothing. The link held as two frames is the split link of lattice gauge theory, known. A relation of slots is not the endpoint obstacle: a dock's 24 slots hold independent contents, so the loops are as random as a hot field (the Haar value), and one content per dock is pure gauge exactly. The knit result is algebra made visible: U = F_q F_p^-1 carries F_p to F_q, so a relation read from the two contents crossing an edge, and applied to them, hands each the other's value. In the slot knit every slot streams, so nothing at an edge stays there: whatever the link holds must be kept at the port, not by the vibe. The relational knit commutes with every frame change because nothing in it ever compares two docks.",
    })
  },
})
