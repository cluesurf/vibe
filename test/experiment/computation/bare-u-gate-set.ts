// The exact gate set of the bare beat U and its universality class (Q1).
//
// W12 read three gates inside bare U in float64 and gave them no code: the role meeting M_meet and its Lie closure on
// the 9-dim S = 1 sector of six like-sign excitations ("dim 80 = su(9)"), a lossless role-SWAP at probability 2/3
// when a pulse passes a doublon, and a Sym^3 CZ near 0.99943 pi (transmission 0.98835). This file certifies or refutes
// each in exact arithmetic over Q(zeta_9) (code/compute/quantum/gate-set). It does not rerun the float search: W12's
// outputs are targets only.
//
// HYPOTHESES, written before the first run:
//   H1  the meeting is the beat's own layer: bare-beat applyRoleMeet, read column by column on two like-sign
//       excitations on one line of a dock, equals (zeta6 / 2) I + ((omega - 1) / 2) SWAP on 2 and on 3 roles, and
//       that gate is exactly unitary with M^3 = I
//   H2  universality on the S = 1 sector: on one '1' among three excitations, g = M_01 M_12 has an eigenvalue angle
//       whose 2 cos is rational and not an integer (so g has infinite order in PU(2)) and a conjugate that does not
//       commute with it, so the closure's identity component is SU(2) on every consecutive triple; then the Lie
//       algebra generated by i P_ab Pi_std(abc) Pi_1 over the four triples of six excitations has real dimension 80
//       (all of su(9)), exactly. W12's own generators (traceless i P_{k,k+1} Pi_1) give 80 too
//   H3  the role-SWAP: F = R_02(u* + i/2) R_12(u* - i/2) at u* = -sqrt3 / 2 maps the doublon-pulse word
//       |(0,1)_Sym> (x) |2> to elastic amplitude a_el = (2 omega + 1) / 3 = i / sqrt3 (probability 1/3, phase +pi/2)
//       and role exchange with probability 2/3 exactly, with no leak out of Sym(0,1) and no loss of norm there
//   H4  the CZ: on Sym^3 F is exactly -1 (phase pi, a root of unity), on the rest of Sym(0,1) exactly zeta6; the
//       W12 numbers 0.99943 pi and 0.98835 are wavepacket readouts and are not certified as exact values
//   H5  Clifford level on the qutrit sector: the meeting lies in none of levels 1 to 3 (a fractional SWAP)
// GATES, fixed before the first run:
//   G0  ring: (1 + zeta6)(1 - omega) / 3 = 1 and (1 + omega)(-omega) = 1, the inverses F uses
//   G1  beat: opposite-sign excitations on one line are left alone by applyRoleMeet (the layer's own negative control)
//   G2  sector: the S = 1 projector of the 15 role words of six excitations is idempotent, rank 9, commutes with every
//       transposition, and holds W12's four logical DFS kets; every generator is traceless (so the dimension is at
//       most 80)
//   G3  density controls: two plain swaps on the triple read a finite angle (2 cos = -1, an integer), the swaps of
//       six excitations close to a finite group of exactly 720, and the generators of one triple alone span 3 (su(2))
//   G4  Clifford controls: Z (x) 1 reads level 1, SWAP level 2, the qutrit T = diag(1, zeta9, zeta9^-1) (x) 1 level 3,
//       on qutrits; on qubits Z (x) 1 level 1, SWAP level 2
//   G5  identical bytes: the whole computation run twice gives the same report
// Verdict: fail if a gate fails (the instrument) or H1 fails; pass if H1 to H5 hold as written; partial otherwise,
// naming the hypothesis that read differently.
//
// WHAT IT MEANS. The meetings, each applied to one chosen adjacent pair, generate a group dense in SU(9) (times
// phases) on the S = 1 sector: universal on that sector, so on W12's 4-dim logical DFS, up to arbitrary precision,
// with no exact finite word for a generic target. In the beat every doubly occupied line meets at once and streaming
// decides which pairs meet, so choosing the pair is a programmer's layout
// (emerges_with_structure). The role-SWAP and the CZ are exact at the level of the Yang R-matrix at u*; that bare U's
// one-line scattering IS that R-matrix (W12's rapidity formula) is W12's float result and is not certified here
// (item Q2 builds the exact scattering table). The role-SWAP needs three distinct roles, which universe.ts allows but
// the Lean model (Bool roles, Vibe/Fock/Gates.lean) does not.
//
// DETERMINISM: no random numbers, no floating point in any decision. Depth L1: exact facts about the beat's gates.

