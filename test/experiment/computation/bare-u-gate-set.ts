const H1 = [2, 3].flatMap(r => [
  `meetEqualsClosedForm${r}`,
  `meetEqualsBeatPlus${r}`,
  `meetEqualsBeatMinus${r}`,
  `meetUnitary${r}`,
  `meetOrderThree${r}`,
])
const H2 = ['witnessOrder', 'witnessTrivial', 'witnessIrrational', 'witnessNonAbelian']
const H3 = ['elasticAmplitude', 'elasticProbabilityThird', 'elasticPhaseQuarterTurn', 'roleSwapTwoThirds', 'lossless', 'noAltLeak', 'fusedNoLeak', 'fusedUnitaryOnSym']
const H4 = ['fusedSpectrumOnSym', 'czMinusOne', 'czIdenticalRoles', 'sMatrixMinusOne', 'stdPhaseZeta6', 'fusedNotUnitaryOnAll', 'r02EigenThird', 'zNormRational', 'zUnitModulus', 'zInfiniteOrder']

const allTrue = (report: Report, names: readonly string[]): boolean => names.every(n => report.ok[n] === true)

export default experiment({
  id: 'computation/bare-u-gate-set',
  code: 'E-CMP-0033',
  title:
    'the exact gate set of the bare beat U: the role meeting M = (zeta6/2) I + ((omega - 1)/2) SWAP is the beat layer itself and exactly unitary of order 3; meetings on adjacent pairs of six like-sign excitations generate a group dense in SU(9) on the S = 1 sector (an irrational eigenvalue angle on every triple and an exact Lie dimension of 80); the Yang-fused role-SWAP has probability 2/3 exactly and the Sym^3 CZ phase is exactly pi, reached only at an irrational momentum, so W12 0.99943 pi is a wavepacket readout; the meeting lies outside Clifford levels 1 to 3',
  category: 'computation',
  substrates: ['{3,4,3,4}'],
  depth: 'L1',
  paper: false,
  run() {
    const first = compute()
    const second = compute()
    const identical = JSON.stringify(first) === JSON.stringify(second)
    const instrument = allTrue(first, INSTRUMENT) && identical
    const h1 = allTrue(first, H1)
    const h2 = allTrue(first, H2) && first.numbers.lieDimension === 80 && first.numbers.lieClosed === 1
    const h3 = allTrue(first, H3)
    const h4 = allTrue(first, H4)
    const h5 = first.numbers.levelMeetQutrit === 0
    const failed = Object.entries(first.ok)
      .filter(([, v]) => !v)
      .map(([k]) => k)
    const status = !instrument || !h1 ? 'fail' : h2 && h3 && h4 && h5 ? 'pass' : 'partial'

    return verdict({
      status,
      claim: !instrument
        ? `an instrument gate failed (${failed.join(', ') || (identical ? 'none' : 'two runs differ')})`
        : !h1
          ? `the meeting gate is not the beat's layer (${failed.join(', ')})`
          : `the meeting is the beat's M_meet layer exactly (2 and 3 roles), unitary, M^3 = I; on a triple 2 cos theta = ${first.exact.twoCos} (rational, not an integer: infinite order) with a non-commuting conjugate${h2 ? '' : ' (H2 read differently)'}, and the Lie algebra of the meetings on the S = 1 sector of six excitations has dimension ${first.numbers.lieDimension} exactly (W12 generators ${first.numbers.lieDimensionW12Generators}), so dense in SU(9); the fused role-SWAP has P_el = ${first.exact.pElastic}, P_swap = ${first.exact.pSwap} and a_el = (2 omega + 1)/3 = i/sqrt3${h3 ? '' : ' (H3 read differently)'}; the CZ is exactly -1 on Sym^3 and zeta6 on Std${h4 ? '' : ' (H4 read differently)'}, reached only at e^(2ip*) of denominator ${first.numbers.zStarDenominator} (infinite order), so 0.99943 pi is not an exact gate value; Clifford level of the meeting on qutrits ${first.numbers.levelMeetQutrit === 0 ? 'none of 1 to 3' : first.numbers.levelMeetQutrit}, on qubits ${first.numbers.levelMeetQubit === 0 ? 'none of 1 to 3' : first.numbers.levelMeetQubit}`,
      metrics: first.numbers,
      control: {
        identicalBytes: identical ? 1 : 0,
        instrumentGates: INSTRUMENT.filter(n => first.ok[n]).length,
        instrumentGatesTotal: INSTRUMENT.length,
        swapGroupOrder: first.numbers.swapGroupOrder ?? 0,
        lieDimensionOneTriple: first.numbers.lieDimensionOneTriple ?? 0,
      },
      notes: `L1, exact over Q(zeta_9). Exact values (6 coordinates on 1..zeta^5 / denominator): meetKeep ${first.exact.meetKeep}, meetSwap ${first.exact.meetSwap}, 2cos ${first.exact.twoCos} (swap control ${first.exact.swapTwoCos}), a_el ${first.exact.elastic}, R_02 eigenvalue ${first.exact.r02Eigen}, z* ${first.exact.zStar}. Failed checks: ${failed.join(', ') || 'none'}. Not certified here: that bare U's one-line scattering is the Yang R-matrix at u* (W12 float, item Q2), and the wavepacket numbers 0.99943 pi and T = 0.98835. Universality needs each adjacent meeting applied alone, a chosen layout (emerges_with_structure).`,
    })
  },
})
