// own pieces forbid.
//
// E-SPN-0051 put the spinor in the role's parity-even doublet. The roadmap's route 3 asks for a token carrying the
// fear walk's Dirac-like motion, a charge and that doublet, and for the minimal content that makes it spin one
// half, charge 1, stable and slower than c on the husk. The token (code/rule/spinor-token) is: the fear walk's two
// slots mixed by the fear coin C = SWAP^(2/3) (a Dirac mass term of angle pi/3), the spin doublet, a charge q = 1
// (love minus fear 3) felt as a Peierls phase, and one husk copy per beat. It is built, not derived: every result
// from it is a stand-in result.
//
// PART A, THE MASS OBSTRUCTION (exact, before any token is chosen). C^3 = SWAP^2 = I. At k = 0 every stream is
// the identity, so a schedule's rest operator is C^n, n the beats per period, and its two rest eigenphases differ
// by 2 pi n / 3 mod 2 pi: the walk is massless at rest exactly when n = 0 mod 3. A schedule the husk's 120 degree
// turn carries to a shift of itself (the only way a product of beats can be covariant beat by beat) has its
// directions in whole orbits of the husk turns, and every orbit of the 9 husk link lines under the 12 tetrahedral
// turns has 3 or 6 members, so n = 0 mod 3. So: A HUSK-SYMMETRIC FEAR WALK IS MASSLESS. The rest mass needs a
// beat outside every orbit, and a husk beat that moves nothing does not exist (every root casts a husk step). The
// token below buys its mass with a depth excursion, a pair of beats along (0, 0, +-1, 1) that returns every column,
// and so breaks the husk symmetry of its schedule by construction. Measured: 'xyz' and 'xyzzyx' have rest gap 0 in
// both modes; the two-dimensional palindrome 'xyyx' of E-FRC-0176 keeps 2 pi / 3 (the control).
//
// THE TOKEN, chosen by a probe before these gates were written (tmp/probe-token.ts, tmp/probe-token2.ts,
// disclosed): schedule x, y, z, up, down in 'locked' mode (the spin decides the direction of each axis copy,
// alpha_a = tau_z sigma_a). Of the schedules probed with three axis beats and whole excursion pairs, every
// palindrome has a saddle for its particle band and every non-palindrome an isotropic spin-averaged bowl with a
// spin splitting quadratic in k; x, y, z, up, down is the shortest of the second kind.
//
// Gates, fixed before the first run:
// A1 C^3 = I to 1e-14
// A2 the 12 husk turns (generated by the axis cycle and the half turn about x) split the 9 husk link lines into
//    orbits whose sizes are all multiples of 3
// A3 rest gap (the smallest nonzero distance between rest eigenphases, 0 when all coincide) is 0 to 1e-12 for 'xyz'
//    and 'xyzzyx' in both modes, and 2 pi / 3 to 1e-12 for 'xyyx' and for the token
// B1 the spin matrix U_q = a - i (b sigma_x + c sigma_y + d sigma_z) of each of the 24 Hurwitz units turns the
//    Pauli vector by a cube rotation (a signed permutation, determinant 1), 12 distinct, with U_(-q) = -U_q
// B2 locked streams are covariant: for all 12 turns R and all three axes, R beat_a R^-1 = beat_(R a) on 8
//    Weyl-sequence states to 1e-12; spectator streams fail for at least one turn (the control)
// B3 for all 8 order-6 units, the turn applied three times is -1 on the token's state space and six times +1, to
//    1e-12
// B4 the token's spin-averaged particle band has an isotropic Hessian at k = 0 (diagonal spread and off-diagonal
