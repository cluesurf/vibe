type Knot = { weights: number[]; chsh: number }
type LikeStudy = {
  found: boolean
  clean: boolean
  knots: Knot[]
  normExact: boolean
  reversed: boolean
  mixes: number
  branchesMax: number
}

function knotsOf(s: LockedState): Knot[] {
  const groups: Branch[][] = []

  for (const b of s.branches) {
    const g = groups.find(o => sameOccupation(o[0]!, b))

    if (g) {
      g.push(b)
    } else {
      groups.push([b])
    }
  }

  const out: Knot[] = []

  for (const g of groups) {
    const open: number[] = []

    for (let i = 0; i < g[0]!.open.length; i++) {
      if (g[0]!.vibe[i] !== 0 && g[0]!.open[i]) {
        open.push(i)
      }
    }

    const k =
      open.length === 2
        ? registerKnot({ branches: g }, open[0]!, open[1]!)
        : undefined

    if (k) {
      out.push({ weights: k.weights, chsh: k.chsh })
    }
  }

  return out
}

function likeStudy(f: LockedFresh): LikeStudy {
  const pick = likePairStart(
    KIND,
    f.tables,
    toWords(vacuumConfiguration(f, 'none')),
    SEARCH,
  )

  if (!pick) {
    return {
      found: false,
      clean: false,
      knots: [],
      normExact: false,
      reversed: false,
      mixes: 0,
      branchesMax: 0,
    }
  }

  const tally = newTally()
  const mt = newMixTally()

  let s: LockedState = lockedState(pick.start)
  let normExact = true
  let knots: Knot[] | undefined
  let branchesMax = 1

  for (let t = 0; t < Q_BEATS; t++) {
    const before = tally.splitMeetings

    s = mixedVetoBeat(KIND, f.tables, s, t, tally, undefined, mt)

    const n = lockedNorm(s)

    normExact = normExact && n.total === n.unit
    branchesMax = Math.max(branchesMax, s.branches.length)

    if (!knots && tally.splitMeetings > before) {
      knots = knotsOf(s)
    }
  }

  let back = s

  for (let t = Q_BEATS - 1; t >= 0; t--) {
    back = mixedVetoBeatBack(KIND, f.tables, back, t)
  }

  const b0 = back.branches[0]
  const reversed =
    back.branches.length === 1 &&
    !!b0 &&
    b0.a === 1n &&
    b0.b === 0n &&
    b0.k === 0 &&
    samePoints(b0, pick.start)

  return {
    found: true,
    clean: pick.clean,
    knots: knots ?? [],
    normExact,
    reversed,
    mixes: mt.mixes,
    branchesMax,
  }
}

