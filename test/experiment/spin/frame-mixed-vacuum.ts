type LoneStudy = {
  mixed: LoneRun
  control: LoneRun
  back: boolean
  again: boolean
  seedFrame: number
}

function loneStudy(
  tables: LockedTables,
  start: Configuration,
  slot: number,
  beats: number,
  side: number,
  husk: number[][],
): LoneStudy {
  const mixed = loneRun({
    kind: KIND,
    tables,
    start,
    slot,
    beats,
    mix: true,
    side,
    husk,
  })
  const control = loneRun({
    kind: KIND,
    tables,
    start,
    slot,
    beats,
    mix: false,
    side,
    husk,
  })
  const again = sameState(
    mixed.final,
    loneRun({
      kind: KIND,
      tables,
      start,
      slot,
      beats,
      mix: true,
      side,
      husk,
    }).final,
  )
  const back = loneRunsBack({
    kind: KIND,
    tables,
    start,
    final: mixed.final,
    beats,
    mix: true,
  })

  return {
    mixed,
    control,
    back,
    again,
    seedFrame: FRAME_OF_LINE[LINE_OF[slot % 24]!]!,
  }
}

