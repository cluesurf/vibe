function axisLine(side: number): {
  tables: LockedTables
  first: number
  second: number
  ring: number[]
  position: Map<number, number>
} {
  const weave = makeColorWeave({ side, table: 'bind' })
  const flat = new Int16Array(weave.mesh.cellCount * 24).fill(
    weave.moves.identity,
  )
  const tables = lockedTables(weave, 'pass', flat)
  const l = LINE_OF[slotOfRoot([1, 0, 0, 1])]!
  const first = LINE_FIRSTS[l]!
  const second = OPPOSITE[first]!
  const ring: number[] = [0]
  const position = new Map<number, number>([[0, 0]])

  for (;;) {
    const next = Math.floor(
      tables.target[ring[ring.length - 1]! * 24 + first]! / 24,
    )

    if (next === 0) {
      break
    }

    position.set(next, ring.length)
    ring.push(next)
  }

  return { tables, first, second, ring, position }
}

function oneBeatAgreement(
  starts: readonly (readonly [number, number][])[],
): { worst: number; offLineWeight: number; L: number } {
  const m = axisLine(6)
  const L = m.ring.length
  const sec: LineSector = {
    flavors: [0, 0, 0],
    statistics: 'fermion',
    D: 3,
    box: L,
    unit: 0,
    mix: true,
  }

  let worst = 0
  let offLineWeight = 0

  for (const st of starts) {
    const c: Configuration = {
      vibe: new Int8Array(m.tables.cells * 24),
      point: new Int8Array(m.tables.cells * 24),
      open: new Uint8Array(m.tables.cells * 24),
      store: new Int8Array(m.tables.cells * 12),
      spoint: new Int8Array(m.tables.cells * 12),
      sopen: new Uint8Array(m.tables.cells * 12),
    }
    const ts = st.map(([x, j]) => ({ x, j, f: 0 }))

    let ringState: RingState = new Map()

    ringState.set(ringKey(ts), {
      ts: ts
        .map(t => ({ ...t }))
        .sort(
          (p, q) =>
            2 * p.x +
            (p.j === 0 ? 1 : 0) -
            (2 * q.x + (q.j === 0 ? 1 : 0)),
        ),
      amp: [1, 0],
    })

    for (const [x, j] of st) {
      const slot = m.ring[x]! * 24 + (j === 0 ? m.first : m.second)

      c.vibe[slot] = 1
      c.open[slot] = 1
    }

    const mixed: Branch[] = []

    for (const b of lockedState(c).branches) {
      mixed.push(...mixBranch(m.tables.cells, b))
    }

    const s = coinedBeat(
      m.tables,
      { branches: mergeBranches(mixed) },
      0,
      { fermion: true },
    )

    ringState = ringBeat(sec, L, ringState)

    const knit = new Map<string, number>()

    for (const b of s.branches) {
      const toks: { x: number; j: number; f: number }[] = []

      let off = false

      for (let i = 0; i < b.vibe.length; i++) {
        if (b.vibe[i] === 0) {
          continue
        }

        const x = m.position.get(Math.floor(i / 24))
        const d = i % 24

        if (x === undefined || (d !== m.first && d !== m.second)) {
          off = true
        } else {
          toks.push({ x, j: d === m.first ? 0 : 1, f: 0 })
        }
      }

      const p = Number(norm(b.a, b.b)) / 4 ** b.k

      if (off) {
        offLineWeight += p / starts.length
        continue
      }

      const key = ringKey(toks)

      knit.set(key, (knit.get(key) ?? 0) + p)
    }

    for (const k of new Set([...knit.keys(), ...ringState.keys()])) {
      const r = ringState.get(k)
      const pr = r ? r.amp[0] ** 2 + r.amp[1] ** 2 : 0

      worst = Math.max(worst, Math.abs((knit.get(k) ?? 0) - pr))
    }
  }

  return { worst, offLineWeight, L }
}

