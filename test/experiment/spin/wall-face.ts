        M[0]! * (M[4]! * M[8]! - M[5]! * M[7]!) -
        M[1]! * (M[3]! * M[8]! - M[5]! * M[6]!) +
        M[2]! * (M[3]! * M[7]! - M[4]! * M[6]!)
