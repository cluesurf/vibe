function mat4MulInt(A: readonly (readonly number[])[], B: readonly (readonly number[])[]): number[][] {
  return [0, 1, 2, 3].map(i =>
    [0, 1, 2, 3].map(j => A[i]![0]! * B[0]![j]! + A[i]![1]! * B[1]![j]! + A[i]![2]! * B[2]![j]! + A[i]![3]! * B[3]![j]!),
  )
}

function mat4Transpose(A: readonly (readonly number[])[]): number[][] {
  return [0, 1, 2, 3].map(i => [0, 1, 2, 3].map(j => A[j]![i]!))
}

function mat4VecInt(A: readonly (readonly number[])[], v: readonly number[]): [number, number, number, number] {
  return [
    A[0]![0]! * v[0]! + A[0]![1]! * v[1]! + A[0]![2]! * v[2]! + A[0]![3]! * v[3]!,
    A[1]![0]! * v[0]! + A[1]![1]! * v[1]! + A[1]![2]! * v[2]! + A[1]![3]! * v[3]!,
    A[2]![0]! * v[0]! + A[2]![1]! * v[1]! + A[2]![2]! * v[2]! + A[2]![3]! * v[3]!,
    A[3]![0]! * v[0]! + A[3]![1]! * v[1]! + A[3]![2]! * v[2]! + A[3]![3]! * v[3]!,
  ]
}

function mat4Det(A: readonly (readonly number[])[]): number {
  const det3 = (m: number[][]): number =>
    m[0]![0]! * (m[1]![1]! * m[2]![2]! - m[1]![2]! * m[2]![1]!) -
    m[0]![1]! * (m[1]![0]! * m[2]![2]! - m[1]![2]! * m[2]![0]!) +
    m[0]![2]! * (m[1]![0]! * m[2]![1]! - m[1]![1]! * m[2]![0]!)
  let d = 0
  for (let c = 0; c < 4; c++) {
    const sub = [1, 2, 3].map(r => [0, 1, 2, 3].filter(j => j !== c).map(j => A[r]![j]!))
    d += (c % 2 === 0 ? 1 : -1) * A[0]![c]! * det3(sub)
  }
  return d
}

function quatMulReal(
  p: readonly [number, number, number, number],
  q: readonly [number, number, number, number],
): [number, number, number, number] {
  return [
    p[0] * q[0] - p[1] * q[1] - p[2] * q[2] - p[3] * q[3],
    p[0] * q[1] + p[1] * q[0] + p[2] * q[3] - p[3] * q[2],
    p[0] * q[2] - p[1] * q[3] + p[2] * q[0] + p[3] * q[1],
    p[0] * q[3] + p[1] * q[2] - p[2] * q[1] + p[3] * q[0],
  ]
}

function leftQuatMat(q: readonly [number, number, number, number]): number[][] {
  const [a, b, c, d] = q
  return [
    [a, -b, -c, -d],
    [b, a, -d, c],
    [c, d, a, -b],
    [d, -c, b, a],
  ]
}

function rightQuatMat(q: readonly [number, number, number, number]): number[][] {
  const [a, b, c, d] = q
  return [
    [a, -b, -c, -d],
    [b, a, d, -c],
    [c, -d, a, b],
    [d, c, -b, a],
  ]
}

