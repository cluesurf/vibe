// GATE N5.1: STRICTLY 1-HOP {3,4,3,4} WARPED CUSP YUKAWAS WITHOUT B_3
// ============================================================================

function runN5_1(originRes: OriginLocalizationResult): void {
  console.log('\n========================================================================')
  console.log('N5.1 [Tier A/B]: STRICTLY 1-HOP {3,4,3,4} WARPED CUSP YUKAWAS (ZERO B_3)')
  console.log('========================================================================')

  // Exact BigInt Steinberg cubic shell recurrence for {3,4,3,4}:
  //   N_0 = 1, N_1 = 18, N_2 = 330, N_3 = 6034,
  //   N_d = 21 N_{d-1} - 51 N_{d-2} + 23 N_{d-3}  (d = 4..13)
  const D_MAX = 13
  const N_SHELLS = D_MAX + 1 // 14 shells: d = 0..13
  const shellsBig: bigint[] = [1n, 18n, 330n, 6034n]
  for (let d = 4; d <= D_MAX; d++) {
    shellsBig.push(21n * shellsBig[d - 1]! - 51n * shellsBig[d - 2]! + 23n * shellsBig[d - 3]!)
  }
  assert(shellsBig.length === 14 && shellsBig[4] === 110298n, 'Steinberg recurrence mismatch')
  const shells = shellsBig.map(Number)
  console.log(`  Exact {3,4,3,4} Steinberg shells: N_0=${shellsBig[0]}, N_1=${shellsBig[1]}, N_4=${shellsBig[4]}, N_13=${shellsBig[13]}`)

  // Exact Q(zeta_9)^+ Galois triplet eta_k = 2 cos(2 pi k / 9) (k = 1, 2, 4)
  // Bulk mass parameters c_a = 1/2 - eta_a / d for discrete cyclotomic d in {9, 12, 18}
  // Strictly 1-hop 13 x 14 bidiagonal operator Q(c_a):
  //   (Q(c_a) u)_n = r_n^{-(1/2 - c_a)/2} u_{n+1} - r_n^{+(1/2 - c_a)/2} u_n   (n = 0..12),
  //   where r_n = N_{n+1} / N_n.
  // Exact zero mode: u_a(n) proportional to (N_n / N_0)^{1/2 - c_a}, normalized sum_n u_a(n)^2 = 1.
  // Husk Yukawa coupling: y_a = |u_a(0)|^2 (zero continuous floats, zero range-3 B_3!).
  const etas: readonly number[] = [
    2 * Math.cos((2 * PI) / 9),
    2 * Math.cos((4 * PI) / 9),
    2 * Math.cos((8 * PI) / 9),
  ]
  const dList: readonly number[] = [9, 12, 18]

  let maxQuInf = 0
  let minKK1 = Infinity
  const ratios31: number[] = []
  let allMonotoneAndBeatG4 = true

  for (const dDenom of dList) {
    const yVals: number[] = []
    let dMinKK1 = Infinity
    for (const eta of etas) {
      const ca = 0.5 - eta / dDenom
      const alpha = 0.5 - ca // = eta / dDenom

      // Build explicit 13 x 14 strictly 1-hop matrix Q(c_a)
      const qDiag = new Float64Array(13) // coeff of u_n in row n
      const qSup = new Float64Array(13) // coeff of u_{n+1} in row n
      for (let n = 0; n < 13; n++) {
        const rn = shells[n + 1]! / shells[n]!
        qDiag[n] = -(rn ** (0.5 * alpha))
        qSup[n] = rn ** (-0.5 * alpha)
      }

      // Exact normalized zero mode u_a(n) ~ (N_n / N_0)^alpha
      const u = new Float64Array(N_SHELLS)
      let norm2 = 0
      for (let n = 0; n < N_SHELLS; n++) {
        u[n] = shells[n]! ** alpha
        norm2 += u[n]! * u[n]!
      }
      const invN = 1 / Math.sqrt(norm2)
      for (let n = 0; n < N_SHELLS; n++) u[n] = u[n]! * invN

      // Verify ||Q(c_a) u||_inf < 1e-14
      for (let n = 0; n < 13; n++) {
        const res = Math.abs(qDiag[n]! * u[n]! + qSup[n]! * u[n + 1]!)
        if (res > maxQuInf) maxQuInf = res
      }

      // Compute first nonzero KK mass m_{KK,1} = sqrt(lambda_min(Q Q^T)) (13 x 13 symmetric tridiagonal)
      const qqtRe = new Float64Array(13 * 13)
      for (let n = 0; n < 13; n++) {
        qqtRe[n * 13 + n] = qDiag[n]! * qDiag[n]! + qSup[n]! * qSup[n]!
        if (n + 1 < 13) {
          const off = qSup[n]! * qDiag[n + 1]!
          qqtRe[n * 13 + (n + 1)] = off
          qqtRe[(n + 1) * 13 + n] = off
        }
      }
      const eigQ = hermitianEig(13, qqtRe, new Float64Array(13 * 13), false)
      const mKK1 = Math.sqrt(Math.max(0, eigQ.values[0]!))
      if (mKK1 < minKK1) minKK1 = mKK1
      if (mKK1 < dMinKK1) dMinKK1 = mKK1

      yVals.push(u[0]! * u[0]!)
    }

    // Sort ascending: y_1 < y_2 < y_3 (eta_1 > eta_2 > 0 > eta_4 => u_1 lightest, u_4 heaviest at husk d=0)
    yVals.sort((a, b) => a - b)
    const y1 = yVals[0]!
    const y2 = yVals[1]!
    const y3 = yVals[2]!
    const r31 = y3 / y1
    const r32 = y3 / y2
    const r21 = y2 / y1
    ratios31.push(r31)
    if (!(y3 > y2 && y2 > y1 && y1 > 0 && r31 > 391.3)) allMonotoneAndBeatG4 = false
    console.log(
      `  d=${String(dDenom).padStart(2)}: y=(${y1.toExponential(3)}, ${y2.toExponential(3)}, ${y3.toExponential(3)}) | y_3/y_1 = ${r31.toExponential(3)} (y_3/y_2=${r32.toFixed(1)}, y_2/y_1=${r21.toFixed(1)}), m_KK1=${dMinKK1.toFixed(4)}`,
    )
  }

  console.log(`  Combined with N4.3 exact 2T_R tree-level rank-1 P_{x=0}: heavy 3rd-gen singlet eig = ${originRes.rank1TopEig.toFixed(6)}, 2'' doublet = ${originRes.rank1ZeroMax.toExponential(1)} (exact tree-level 0)`)
  console.log(`  Max ||Q u||_inf = ${maxQuInf.toExponential(2)} (< 1e-14), min m_{KK,1} = ${minKK1.toFixed(6)} (> 0.22)`)

  recordCheck(
    'N5.1',
    'Strictly 1-hop {3,4,3,4} warped cusp Yukawas (ZERO B_3, ZERO floats) + exact 2T_R rank-1 3rd gen',
    'A/B',
    maxQuInf < 1e-14 &&
      minKK1 > 0.22 &&
      allMonotoneAndBeatG4 &&
      originRes.rank1ZeroMax < 1e-14 &&
      originRes.rank1TopEig > 0.04,
    `||Qu||_inf=${maxQuInf.toExponential(1)}, m_KK1=${minKK1.toFixed(4)}, y3/y1=[d=9:${ratios31[0]!.toExponential(2)}, d=12:${ratios31[1]!.toExponential(2)}, d=18:${ratios31[2]!.toFixed(1)}] (>G4 391.3), treeRank1=${originRes.rank1TopEig.toFixed(4)}`,
  )
}

